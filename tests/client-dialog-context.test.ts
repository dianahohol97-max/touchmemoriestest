import { describe, expect, it } from 'vitest';
import {
    NO_DIALOG_LINE,
    buildDialogContext,
    type ClientDialogMatch,
} from '@/lib/chatbot/client-chat-lookup';
import { findSpokenColour, findVelourCode } from '@/lib/chatbot/work-questions';

/**
 * Переписка клієнта у відповідях Софії.
 *
 * Тест існує через два різні провали, обидва справжні.
 *
 * Перший: відсутність даних, подана порожнечею, перетворюється на вигадку.
 * Спитана про пошту клієнтки, у якої email не заповнений, Софія склала
 * правдоподібну адресу з її імені, і Діана мало не написала на неї. Лікувалося
 * це явним рядком «клієнт НЕ лишив email» — і рівно те саме правило тепер діє
 * для переписки: коли діалогу немає, у факти йде речення про це, а не порожній
 * рядок.
 *
 * Другий: діалог знаходили пошуком за іменем, і знаходили чужий. 14.09.2026
 * перевірка на бойових даних дала 22 збіги за іменем, з яких добра половина
 * вела на переписку іншої людини. Тепер читається тільки привʼязаний діалог, а
 * привʼязка за іменем не читається взагалі.
 *
 * Живу відповідь моделі тут перевірити неможливо — це мережевий виклик. Тому
 * перевіряється те, що моделі ВІДДАЮТЬ, і воно однозначне: або переписка з
 * підписом, чия вона, або пряма заява, що переписки немає.
 */

const MATCH: ClientDialogMatch = {
    conversationId: '00000000-0000-0000-0000-000000000001',
    who: 'Катерина',
    platform: 'telegram',
    confidence: 'phone',
};

describe('коли діалог є', () => {
    it('переписка підписана тим, чия вона, і чим це доведено', () => {
        const out = buildDialogContext(MATCH, '[01.09] Клієнт: колір в-11\n[01.09] Ми: прийняли');
        expect(out).toContain('Переписка з клієнтом «Катерина» у telegram');
        expect(out).toContain('звірено за номером телефону');
        expect(out).toContain('в-11');
        expect(out).not.toBe(NO_DIALOG_LINE);
    });

    it('номер замовлення в діалозі підписується інакше, ніж телефон', () => {
        const out = buildDialogContext({ ...MATCH, confidence: 'order' }, '[01.09] Клієнт: TM-001194');
        expect(out).toContain('у діалозі названо номер замовлення');
        expect(out).not.toContain('звірено за номером телефону');
    });
});

describe('коли діалогу немає', () => {
    it('повертається не порожнє, а заява про відсутність', () => {
        expect(buildDialogContext(null, '')).toBe(NO_DIALOG_LINE);
        expect(NO_DIALOG_LINE.length).toBeGreaterThan(0);
    });

    it('порожня переписка при знайденому діалозі — теж відсутність', () => {
        // Розмова існує, але всі повідомлення без тексту (самі фото). Видавати
        // підпис «Переписка з клієнтом …» над порожнечею не можна: модель
        // прочитає це як «переписку показали, там нічого» і почне добудовувати.
        expect(buildDialogContext(MATCH, '')).toBe(NO_DIALOG_LINE);
    });

    it('заява прямо забороняє додавати щось «з чату»', () => {
        expect(NO_DIALOG_LINE).toContain('не привʼязано');
        expect(NO_DIALOG_LINE).toContain('прямо скажи, що переписки не знайдено');
    });

    it('сама заява не читається як колір або код велюру', () => {
        // Рядок про відсутність їде в ті самі витягачі, що й переписка. Якби він
        // містив слово «колір» чи щось схоже на «В-11», Софія відповіла б
        // кольором, узятим із власного службового речення.
        expect(findVelourCode(NO_DIALOG_LINE)).toBeNull();
        expect(findSpokenColour(NO_DIALOG_LINE)).toBeNull();
    });
});
