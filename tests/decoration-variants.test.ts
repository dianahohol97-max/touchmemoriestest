import { describe, expect, it } from 'vitest';
import { readDecorationType, stripUnusedDecorationVariants } from '@/lib/orders/decoration-variants';

/**
 * Відсів варіантів оздоблення, яких не замовляли.
 *
 * Дві помилки, які тут закріплені, мовчали рівно тому, що акрил через цей
 * конструктор іще ніхто не замовляв (Діана, 16.09.2026). Обидві виявилися б
 * на першому ж такому замовленні, і виявилися б як зникла опція в оплаченому
 * замовленні.
 */
describe('тип оздоблення', () => {
    /**
     * У живих даних ключі йдуть у такому порядку: Розмір, Корінець,
     * Оздоблення, Колір велюру, Варіант акрилу, Тип оздоблення… Тобто сусід
     * «Оздоблення» стоїть ПЕРШИМ, і саме він у пʼяти замовленнях каже
     * «Без оздоблення», поки «Тип оздоблення» каже «Металева вставка».
     */
    it('читає «Тип оздоблення», а не сусіда, що стоїть раніше', () => {
        const bag = {
            'Розмір': '30х20',
            'Оздоблення': 'Без оздоблення',
            'Варіант акрилу': '100×100 мм',
            'Тип оздоблення': 'Металева вставка',
        };

        expect(readDecorationType(bag)).toBe('Металева вставка');
    });

    it('без «Тип оздоблення» бере те, що є', () => {
        expect(readDecorationType({ 'Декорація обкладинки': 'Акрил' })).toBe('Акрил');
        expect(readDecorationType({ 'Оздоблення': 'Гравірування' })).toBe('Гравірування');
        expect(readDecorationType({})).toBe('');
    });
});

describe('відсів варіантів', () => {
    /**
     * Головний випадок обох помилок разом: клієнт обрав акрил, а сусідній
     * ключ каже «Без оздоблення». Стара умова читала сусіда і видаляла саме
     * той варіант, який клієнт обрав і оплатив.
     */
    it('акриловому замовленню лишає варіант акрилу', () => {
        const bag: Record<string, any> = {
            'Оздоблення': 'Без оздоблення',
            'Тип оздоблення': 'Акрил',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
        };

        const removed = stripUnusedDecorationVariants(bag);

        expect(bag['Варіант акрилу']).toBe('100×100 мм');
        expect(bag['Варіант фотовставки']).toBeUndefined();
        expect(removed).toEqual(['Варіант фотовставки']);
    });

    /**
     * Друга помилка окремо: «фото або вставк» ловило слово «вставка»
     * всередині «Металева вставка», тож металевим замовленням фотовставка
     * лишалася завжди. Так і сталося з TM-001296 від 10.09.2026.
     */
    it('металевій вставці не лишає фотовставку', () => {
        const bag: Record<string, any> = {
            'Тип оздоблення': 'Металева вставка',
            'Варіант оздоблення': '90×50 золотий',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
        };

        stripUnusedDecorationVariants(bag);

        expect(bag['Варіант оздоблення']).toBe('90×50 золотий');
        expect(bag['Варіант акрилу']).toBeUndefined();
        expect(bag['Варіант фотовставки']).toBeUndefined();
    });

    it('фотовставці лишає саме фотовставку', () => {
        const bag: Record<string, any> = {
            'Тип оздоблення': 'Фотовставка',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
        };

        stripUnusedDecorationVariants(bag);

        expect(bag['Варіант фотовставки']).toBe('100×100 мм');
        expect(bag['Варіант акрилу']).toBeUndefined();
    });

    it('гравіруванню не лишає нічого зайвого', () => {
        const bag: Record<string, any> = {
            'Тип оздоблення': 'Гравірування',
            'Варіант акрилу': 'acryl_100x100',
            'Варіант фотовставки': 'foto_100x100',
        };

        stripUnusedDecorationVariants(bag);

        expect(Object.keys(bag)).toEqual(['Тип оздоблення']);
    });

    it('порожній набір і відсутній обʼєкт не ламають нічого', () => {
        expect(stripUnusedDecorationVariants({})).toEqual([]);
        expect(stripUnusedDecorationVariants(undefined as any)).toEqual([]);
    });
});
