import { describe, expect, it } from 'vitest';
import { matchCoverType } from '@/lib/editor/pricing';

/**
 * Яку обкладинку означає товар сайту.
 *
 * Від цього залежить відсів у генераторі варіантів для звірки каталогу з
 * KeyCRM: він питає таблицю цін, чи існує пара «розмір + розвороти», і
 * ключем туди йде саме назва обкладинки. Не впізнали обкладинку — відсів
 * вимикається, і в мапу знову поїдуть неіснуючі пари.
 *
 * Тому тут закріплені всі товари з вибором кількості сторінок, які є на
 * сайті: чотири фотокниги мусять упізнаватися, а журнали, книги побажань і
 * Travel Book мусять давати null, бо в них обкладинка не з цього словника і
 * відсів до них не стосується.
 */
const PRODUCTS: Array<[slug: string, name: string, cover: string | null]> = [
    ['photobook-printed', 'Фотокнига з друкованою обкладинкою', 'Друкована'],
    ['photobook-fabric', 'Фотокнига з тканинною обкладинкою', 'Тканина'],
    ['photobook-leatherette', 'Фотокнига з обкладинкою зі шкірзамінника', 'Шкірзамінник'],
    ['photobook-velour', 'Фотокнига з велюровою обкладинкою', 'Велюр'],
    ['graduation-photobook', 'Випускна фотокнига', 'Випускна'],
    ['fotozhurnal-tverd-obkladynka', 'Фотожурнал з твердою обкладинкою', null],
    ['personalized-glossy-magazine', "Глянцевий журнал з м'якою обкладинкою", null],
    ['travelbook-20x30', 'Travel Book', null],
    ['wishbook', 'Книга побажань', null],
    ['guestbook-kids', 'Книга побажань дитяча', null],
];

describe('обкладинка за товаром сайту', () => {
    it.each(PRODUCTS)('%s → %s', (slug, name, cover) => {
        expect(matchCoverType(`${slug} ${name}`)).toBe(cover);
    });

    /**
     * «Випускна» мусить перевірятися РАНІШЕ за «друкована»: у випускної
     * фотокниги обкладинка теж друкована, і якби порядок був інший, вона
     * звірялася б із цінами не своєї обкладинки.
     */
    it('випускна не плутається з друкованою', () => {
        expect(matchCoverType('graduation-photobook Випускна фотокнига з друкованою обкладинкою')).toBe('Випускна');
    });
});
