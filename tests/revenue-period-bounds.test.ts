import { describe, expect, it } from 'vitest';
import {
    dayEndIso,
    dayStartIso,
    kyivDateOnly,
    monthRange,
    periodRange,
} from '@/lib/orders/revenue-period';

/**
 * Межі періоду у звітності.
 *
 * Тест існує через 15.09.2026, коли сторінка витрат і звіт P&L показали за
 * той самий вересень 307 757 ₴ і 327 338 ₴. Правило доходу вже було спільне —
 * розійшлися саме межі: кожен екран будував їх сам, і обидва рахунки
 * спиралися на `new Date(...).toISOString().split('T')[0]`, який у зоні UTC+3
 * віддає вчорашню дату.
 *
 * Тут перевіряється не сума, а те, що доба починається й закінчується там, де
 * має. Помилка в межі коштує рівно однієї доби обігу, і мовчить.
 */

describe('межі доби', () => {
    it('починає добу опівночі за Києвом, а не за Гринвічем', () => {
        // Літній час, UTC+3: перше вересня о 00:00 у Києві — це 31 серпня
        // о 21:00 за Гринвічем.
        expect(dayStartIso('2026-09-01')).toBe('2026-08-31T21:00:00.000Z');
        expect(dayEndIso('2026-09-30')).toBe('2026-09-30T20:59:59.999Z');
    });

    it('тримає зимовий зсув UTC+2', () => {
        expect(dayStartIso('2026-01-01')).toBe('2025-12-31T22:00:00.000Z');
        expect(dayEndIso('2026-01-31')).toBe('2026-01-31T21:59:59.999Z');
    });

    it('включає останню мить останнього дня', () => {
        // Через це `.lte()` не відрізає добу: раніше межею була опівніч
        // останнього дня, і липень недорахував 51 595 ₴.
        expect(dayEndIso('2026-07-31').endsWith('59.999Z')).toBe(true);
        expect(new Date(dayEndIso('2026-07-31')).getTime())
            .toBeLessThan(new Date(dayStartIso('2026-08-01')).getTime() + 1);
    });

    it('зводить повний ISO до київської доби, а не до доби сервера', () => {
        // 31 серпня о 22:00 за Гринвічем — це вже перше вересня в Києві.
        expect(kyivDateOnly(new Date('2026-08-31T22:00:00.000Z'))).toBe('2026-09-01');
        expect(dayStartIso('2026-08-31T22:00:00.000Z')).toBe('2026-08-31T21:00:00.000Z');
    });
});

describe('діапазони періодів', () => {
    it('віддає місяць цілим', () => {
        expect(monthRange(2026, 9)).toEqual({ start: '2026-09-01', end: '2026-09-30' });
        expect(monthRange(2026, 2)).toEqual({ start: '2026-02-01', end: '2026-02-28' });
        expect(monthRange(2024, 2)).toEqual({ start: '2024-02-01', end: '2024-02-29' });
    });

    it('переходить через межу року в обидва боки', () => {
        // Графік за дванадцять місяців відлічує назад від поточного, тож
        // нульовий і від'ємний номер місяця тут звичайна річ.
        expect(monthRange(2026, 0)).toEqual({ start: '2025-12-01', end: '2025-12-31' });
        expect(monthRange(2026, -2)).toEqual({ start: '2025-10-01', end: '2025-10-31' });
        expect(monthRange(2026, 13)).toEqual({ start: '2027-01-01', end: '2027-01-31' });
    });

    it('рахує квартал і рік від київської дати', () => {
        const ref = new Date('2026-09-15T12:00:00.000Z');
        expect(periodRange('month', ref)).toEqual({ start: '2026-09-01', end: '2026-09-30' });
        expect(periodRange('quarter', ref)).toEqual({ start: '2026-07-01', end: '2026-09-30' });
        expect(periodRange('year', ref)).toEqual({ start: '2026-01-01', end: '2026-12-31' });
    });

    it("не з'їжджає на добу назад у ніч перед першим числом", () => {
        // Саме на цьому зламався звіт: о 21:30 за Гринвічем 31 серпня в Києві
        // вже перше вересня, і місяцем має бути вересень.
        const ref = new Date('2026-08-31T21:30:00.000Z');
        expect(periodRange('month', ref)).toEqual({ start: '2026-09-01', end: '2026-09-30' });
    });
});
