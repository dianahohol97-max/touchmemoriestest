import { describe, expect, it } from 'vitest';
import { cleanItemOptions, resolveDecoration } from '@/lib/orders/item-options';

/**
 * Оздоблення в позиції замовлення: що читається як обране і що прибирається.
 *
 * Прибирач у проєкті ОДИН — cleanItemOptions — і його кличуть три місця:
 * кошик (/api/orders/submit), картка товару і модалка «з дизайнером». Ці
 * тести стерегли вужчу копію, яка жила окремо один день; вони перенесені на
 * спільну функцію, щоб покриття не зникло разом із модулем.
 *
 * Відсів варіантів оздоблення, яких не замовляли.
 *
 * Дві помилки, які тут закріплені, мовчали рівно тому, що акрил через цей
 * конструктор іще ніхто не замовляв (Діана, 16.09.2026). Обидві виявилися б
 * на першому ж такому замовленні, і виявилися б як зникла опція в оплаченому
 * замовленні.
 */
describe('тип оздоблення', () => {
    /**
     * У живих даних ключі йдуть у такому порядку: Розмір, Корінець,
     * Оздоблення, Колір велюру, Варіант акрилу, Тип оздоблення… Тобто сусід
     * «Оздоблення» стоїть ПЕРШИМ, і саме він у пʼяти замовленнях каже
     * «Без оздоблення», поки «Тип оздоблення» каже «Металева вставка».
     */
    it('читає «Тип оздоблення», а не сусіда, що стоїть раніше', () => {
        const bag = {
            'Розмір': '30х20',
            'Оздоблення': 'Без оздоблення',
            'Варіант акрилу': '100×100 мм',
            'Тип оздоблення': 'Металева вставка',
        };

        expect(resolveDecoration(bag).label).toBe('Металева вставка');
        expect(resolveDecoration(bag).sourceKey).toBe('Тип оздоблення');
    });

    it('без «Тип оздоблення» бере те, що є', () => {
        expect(resolveDecoration({ 'Декорація обкладинки': 'Акрил' }).label).toBe('Акрил');
        expect(resolveDecoration({ 'Оздоблення': 'Гравірування' }).label).toBe('Гравірування');
        expect(resolveDecoration({}).label).toBe('');
    });
});

describe('відсів варіантів', () => {
    /**
     * Головний випадок обох помилок разом: клієнт обрав акрил, а сусідній
     * ключ каже «Без оздоблення». Стара умова читала сусіда і видаляла саме
     * той варіант, який клієнт обрав і оплатив.
     */
    it('акриловому замовленню лишає варіант акрилу', () => {
        const bag: Record<string, any> = {
            'Оздоблення': 'Без оздоблення',
            'Тип оздоблення': 'Акрил',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
        };

        const cleaned = cleanItemOptions(bag);

        expect(cleaned['Варіант акрилу']).toBe('100×100 мм');
        expect(cleaned['Варіант фотовставки']).toBeUndefined();
        // Брехливий сусід теж не доїжджає: обране назване новим ключем.
        expect(cleaned['Оздоблення']).toBeUndefined();
        expect(cleaned['Тип оздоблення']).toBe('Акрил');
    });

    /**
     * Друга помилка окремо: «фото або вставк» ловило слово «вставка»
     * всередині «Металева вставка», тож металевим замовленням фотовставка
     * лишалася завжди. Так і сталося з TM-001296 від 10.09.2026.
     */
    it('металевій вставці не лишає фотовставку', () => {
        const bag: Record<string, any> = {
            'Тип оздоблення': 'Металева вставка',
            'Варіант оздоблення': '90×50 золотий',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
        };

        const cleaned = cleanItemOptions(bag);

        expect(cleaned['Варіант оздоблення']).toBe('90×50 золотий');
        expect(cleaned['Варіант акрилу']).toBeUndefined();
        expect(cleaned['Варіант фотовставки']).toBeUndefined();
    });

    it('фотовставці лишає саме фотовставку', () => {
        const bag: Record<string, any> = {
            'Тип оздоблення': 'Фотовставка',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
        };

        const cleaned = cleanItemOptions(bag);

        expect(cleaned['Варіант фотовставки']).toBe('100×100 мм');
        expect(cleaned['Варіант акрилу']).toBeUndefined();
    });

    it('гравіруванню не лишає нічого зайвого', () => {
        const bag: Record<string, any> = {
            'Тип оздоблення': 'Гравірування',
            'Варіант акрилу': 'acryl_100x100',
            'Варіант фотовставки': 'foto_100x100',
        };

        expect(Object.keys(cleanItemOptions(bag))).toEqual(['Тип оздоблення']);
    });

    it('порожній набір і відсутній обʼєкт не ламають нічого', () => {
        expect(cleanItemOptions({})).toEqual({});
        expect(cleanItemOptions(undefined as any)).toEqual({});
    });
});

/**
 * Книги побажань не мають змінитися від того, що порядок ключів став один на
 * всі родини товарів.
 *
 * Їхній діалект — «Декорація обкладинки», і ключ «Тип оздоблення» в них не
 * зустрічається ЖОДНОГО разу: перевірено запитом по всій базі, перетин
 * дорівнює нулю. Тут закріплені всі чотири значення, які реально трапляються
 * в замовленнях книг побажань.
 */
describe('книги побажань не змінюються', () => {
    const WISHBOOK_DECOS: Array<[string, string]> = [
        ['гравірування', 'graviruvannya'],
        ['Акрилова вставка', 'acryl'],
        ['Металева вставка', 'metal'],
        ['Флекс (друк кольором)', 'flex'],
    ];

    it.each(WISHBOOK_DECOS)('«%s» читається так само', (value, kind) => {
        const resolved = resolveDecoration({ 'Декорація обкладинки': value, 'Розмір книги': '23х23' });

        expect(resolved.label).toBe(value);
        expect(resolved.kind).toBe(kind);
        expect(resolved.sourceKey).toBe('Декорація обкладинки');
    });

    /**
     * Металева вставка в книзі побажань не має ставати фотовставкою — саме
     * ця пастка зі словом «вставка» ховала метал в адмінці.
     */
    it('металева вставка лишається металом', () => {
        expect(resolveDecoration({ 'Декорація обкладинки': 'Металева вставка' }).kind).toBe('metal');
    });
});

/**
 * Фотокниги з конструктора — та сама суперечлива пара, через яку друкарські
 * маршрути ухвалювали рішення за брехливим ключем.
 */
describe('фотокниги з конструктора', () => {
    it('фотовставка впізнається попри сусіда «Без оздоблення»', () => {
        const opts = {
            'Оздоблення': 'none',
            'Тип оздоблення': 'Фотовставка',
            'Варіант фотовставки': '100×100 мм',
        };

        expect(resolveDecoration(opts).kind).toBe('photovstavka');
        expect(resolveDecoration(opts).label).toBe('Фотовставка');
    });

    it('гравірування впізнається попри сусіда «none»', () => {
        expect(resolveDecoration({ 'Оздоблення': 'none', 'Тип оздоблення': 'Гравірування' }).kind)
            .toBe('graviruvannya');
    });

    /**
     * Коли обидва ключі кажуть про оздоблення, але РІЗНЕ, модуль не обирає
     * мовчки — він піднімає прапорець. Мовчазний вибір одного з двох і є те,
     * через що на верстат може поїхати не та вставка.
     */
    it('справжню суперечність називає вголос', () => {
        const resolved = resolveDecoration({ 'Тип оздоблення': 'Металева вставка', 'Оздоблення': 'Акрилова вставка' });

        expect(resolved.conflict).toBe(true);
    });
});

/**
 * Те, що спільний прибирач додає понад стару вужчу копію в кошику.
 *
 * Обидва приклади — живі позиції з кошика: у них є ключі з порожнім
 * значенням, які в картці замовлення читаються рядком «Колір напису: » без
 * нічого. За 120 днів таких позицій пʼять зі 127.
 */
describe('що саме змінюється в кошику', () => {
    it('порожні значення більше не доїжджають у позицію', () => {
        const cleaned = cleanItemOptions({
            'Колір напису': '',
            'Текст напису': 'Аіша(булка)💋',
            'Шрифт напису': '',
            'Розмір напису': 'Великий',
            'Колір обкладинки': 'Зелений',
        });

        expect(Object.keys(cleaned)).toEqual(['Текст напису', 'Розмір напису', 'Колір обкладинки']);
    });

    it('сертифікат без отримувача не несе порожнього рядка', () => {
        const cleaned = cleanItemOptions({
            'Номер': 'TM-2026-M509',
            'Формат': 'Друкований',
            'Отримувач': '',
            'Термін дії': '8 вересня 2027 р.',
            'Тип сертифікату': 'На суму 1500 ₴',
        });

        expect(cleaned['Отримувач']).toBeUndefined();
        expect(cleaned['Номер']).toBe('TM-2026-M509');
    });

    /**
     * Порядок ключів менеджер читає згори вниз, і прибирач його зберігає —
     * інакше картка замовлення перетасовувалася б на кожному збереженні.
     */
    it('порядок решти ключів не змінюється', () => {
        const cleaned = cleanItemOptions({
            'Розмір': '30х20', 'Корінець': 'standard', 'Оздоблення': 'none',
            'Колір велюру': 'Молочний (В-01)', 'Тип оздоблення': 'Гравірування',
            'Кількість сторінок': 30,
        });

        expect(Object.keys(cleaned)).toEqual([
            'Розмір', 'Корінець', 'Колір велюру', 'Тип оздоблення', 'Кількість сторінок',
        ]);
    });
});
