import { describe, expect, it } from 'vitest';
import { PHOTOBOOK_MIN_PAGES, minPagesForSize, photobookSizeKey } from '@/lib/pricing/photobook-min-pages';

/**
 * Мінімальна кількість розворотів для розміру фотокниги.
 *
 * Числа виробничі, не технічні: 30×30 на шість розворотів не роблять
 * (Діана, 15.09.2026). Раніше ця таблиця стояла в картці товару двічі — у
 * фільтрі списку і в підтягуванні вже обраного значення, — і трималася
 * однаковою лише доти, доки ніхто не правив одну копію.
 */
describe('мінімуми розворотів', () => {
    it('тримає виробничі мінімуми для всіх пʼяти розмірів', () => {
        expect(PHOTOBOOK_MIN_PAGES).toEqual({
            '20x20': 6,
            '25x25': 8,
            '20x30': 10,
            '30x20': 10,
            '30x30': 16,
        });
    });

    /**
     * Розмір приходить у картку трьома написаннями, і саме на цьому колись
     * ламалися пошуки по ключу: кирилична «х» виглядає як латинська «x».
     */
    it('однаково читає кириличну х, латинську x і знак множення', () => {
        for (const spelling of ['30х30', '30x30', '30×30', '30×30 см', ' 30Х30 ']) {
            expect(minPagesForSize(spelling)).toBe(16);
        }
        expect(photobookSizeKey('20×30 см')).toBe('20x30');
    });

    it('30×30 на шість розворотів недосяжне, на шістнадцять — дозволене', () => {
        expect(6).toBeLessThan(minPagesForSize('30×30'));
        expect(16).toBeGreaterThanOrEqual(minPagesForSize('30×30'));
    });

    it('невідомий розмір дає нуль, а не тихий мінімум', () => {
        expect(minPagesForSize('40×40')).toBe(0);
        expect(minPagesForSize('')).toBe(0);
    });
});
