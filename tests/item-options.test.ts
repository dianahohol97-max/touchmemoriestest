import { describe, it, expect } from 'vitest';
import {
    cleanItemOptions,
    decoKindOf,
    describeItemOptions,
    resolveDecoration,
} from '@/lib/orders/item-options';

/**
 * Опис позиції не має суперечити сам собі.
 *
 * TM-001296: у позиції одночасно лежали «Оздоблення: Без оздоблення»,
 * «Тип оздоблення: Металева вставка», «Варіант оздоблення: 90×50 золотий» і
 * два чужі варіанти (акрил і фотовставка по 100×100 мм), які клієнтка
 * перебирала дорогою до металу. Картка замовлення читала це буквально й
 * казала «без оздоблення» поруч із розміром вставки.
 */
const TM_001296 = {
    'Розмір': '30х30',
    'Корінець': 'standard',
    'Оздоблення': 'Без оздоблення',
    'Варіант акрилу': '100×100 мм',
    'Тип оздоблення': 'Металева вставка',
    'Варіант оздоблення': '90×50 золотий',
    'Кількість сторінок': 50,
    'Варіант фотовставки': '100×100 мм',
    'Калька перед першою сторінкою': 'Без кальки',
};

describe('decoKindOf', () => {
    it('розрізняє метал і фотовставку', () => {
        // «Металева вставка» містить слово «вставка», і перевірка на
        // фотовставку, поставлена раніше, забирала метал собі.
        expect(decoKindOf('Металева вставка')).toBe('metal');
        expect(decoKindOf('Фотовставка')).toBe('photovstavka');
        expect(decoKindOf('foto_100x100')).toBe('photovstavka');
    });

    it('порожнє значення і «Без оздоблення» — це відсутність оздоблення', () => {
        expect(decoKindOf('')).toBe('none');
        expect(decoKindOf(null)).toBe('none');
        expect(decoKindOf('none')).toBe('none');
        expect(decoKindOf('Без оздоблення')).toBe('none');
    });

    it('знає решту родини оздоблень', () => {
        expect(decoKindOf('Акрил')).toBe('acryl');
        expect(decoKindOf('Друк кольором')).toBe('flex');
        expect(decoKindOf('Гравірування')).toBe('graviruvannya');
    });
});

describe('resolveDecoration', () => {
    it('бере справжнє оздоблення, а не залишок старого селекта', () => {
        const deco = resolveDecoration(TM_001296);
        expect(deco.kind).toBe('metal');
        expect(deco.label).toBe('Металева вставка');
        expect(deco.sourceKey).toBe('Тип оздоблення');
        expect(deco.variant).toBe('90×50 золотий');
        expect(deco.conflict).toBe(false);
    });

    it('читає старий ключ, коли нового немає', () => {
        const deco = resolveDecoration({ 'Оздоблення': 'Акрил', 'Варіант акрилу': 'Ø145 мм' });
        expect(deco.kind).toBe('acryl');
        expect(deco.sourceKey).toBe('Оздоблення');
        expect(deco.variant).toBe('Ø145 мм');
    });

    it('два різні оздоблення — це конфлікт, а не привід обрати одне мовчки', () => {
        const deco = resolveDecoration({ 'Оздоблення': 'Акрил', 'Тип оздоблення': 'Металева вставка' });
        expect(deco.conflict).toBe(true);
    });
});

describe('cleanItemOptions', () => {
    it('прибирає суперечність із TM-001296', () => {
        const clean = cleanItemOptions(TM_001296);
        expect(clean['Оздоблення']).toBeUndefined();
        expect(clean['Тип оздоблення']).toBe('Металева вставка');
        expect(clean['Варіант оздоблення']).toBe('90×50 золотий');
    });

    it('прибирає варіанти оздоблень, яких не купували', () => {
        const clean = cleanItemOptions(TM_001296);
        expect(clean['Варіант акрилу']).toBeUndefined();
        expect(clean['Варіант фотовставки']).toBeUndefined();
    });

    it('не чіпає решту позиції і зберігає порядок', () => {
        expect(Object.keys(cleanItemOptions(TM_001296))).toEqual([
            'Розмір',
            'Корінець',
            'Тип оздоблення',
            'Варіант оздоблення',
            'Кількість сторінок',
            'Калька перед першою сторінкою',
        ]);
    });

    it('без оздоблення жоден варіант не лишається', () => {
        const clean = cleanItemOptions({
            'Оздоблення': 'Без оздоблення',
            'Варіант акрилу': '100×100 мм',
            'Варіант фотовставки': '100×100 мм',
            'Варіант оздоблення': '',
            'Розмір': '20х20',
        });
        expect(Object.keys(clean)).toEqual(['Оздоблення', 'Розмір']);
    });

    it('колір напису лишається лише там, де є напис флексом', () => {
        expect(cleanItemOptions({ 'Тип оздоблення': 'Друк кольором', 'Колір напису': 'gold' })['Колір напису']).toBe('gold');
        expect(cleanItemOptions({ 'Тип оздоблення': 'Металева вставка', 'Колір напису': 'gold' })['Колір напису']).toBeUndefined();
    });

    it('справжній варіант металу лишається навіть без універсального ключа', () => {
        const clean = cleanItemOptions({
            'Тип оздоблення': 'Металева вставка',
            'Варіант металевої вставки': '250×70 срібний',
        });
        expect(clean['Варіант металевої вставки']).toBe('250×70 срібний');
    });

    it('той самий варіант не показуємо двічі', () => {
        const clean = cleanItemOptions({
            'Тип оздоблення': 'Металева вставка',
            'Варіант оздоблення': '90×50 золотий',
            'Варіант металевої вставки': '90×50 золотий',
        });
        expect(clean['Варіант металевої вставки']).toBeUndefined();
        expect(clean['Варіант оздоблення']).toBe('90×50 золотий');
    });

    it('конфлікт лишається на видноті', () => {
        const clean = cleanItemOptions({ 'Оздоблення': 'Акрил', 'Тип оздоблення': 'Металева вставка' });
        expect(clean['Оздоблення']).toBe('Акрил');
        expect(clean['Тип оздоблення']).toBe('Металева вставка');
    });

    it('порожні значення не описують нічого', () => {
        expect(cleanItemOptions({ 'Корінець': '', 'Розмір': '30х30' })).toEqual({ 'Розмір': '30х30' });
    });
});

describe('describeItemOptions', () => {
    it('перекладає коди конструктора людською мовою', () => {
        const rows = describeItemOptions(TM_001296);
        expect(rows.find(r => r.key === 'Корінець')?.value).toBe('Стандартний');
        expect(rows.find(r => r.key === 'Тип оздоблення')?.value).toBe('Металева вставка');
    });

    it('«none» означає різне на різних полях', () => {
        const rows = describeItemOptions({ 'Калька перед першою сторінкою': 'none', 'Тип оздоблення': 'none' });
        expect(rows.find(r => r.key === 'Калька перед першою сторінкою')?.value).toBe('Без кальки');
        expect(rows.find(r => r.key === 'Тип оздоблення')?.value).toBe('Без оздоблення');
    });
});

describe('покриття обкладинки', () => {
    it('глянець не називаємо двічі', () => {
        const clean = cleanItemOptions({
            'Ламінація обкладинки': 'Глянцева',
            'Тип обкладинки': 'Глянцева',
            'coverType': 'Глянцева',
        });
        expect(Object.keys(clean)).toEqual(['Ламінація обкладинки']);
    });

    it('матеріал обкладинки під тим самим ключем лишається', () => {
        const clean = cleanItemOptions({ 'Ламінація обкладинки': 'Матова', 'coverType': 'Велюр' });
        expect(clean['coverType']).toBe('Велюр');
    });
});

describe('рядок у картці замовлення', () => {
    it('TM-001296 читається без суперечності', () => {
        // Саме той рядок, який Діана побачила в адмінці 13.09.2026 — тепер він
        // називає одне оздоблення й один розмір вставки.
        const line = describeItemOptions(TM_001296).map(o => `${o.label}: ${o.value}`).join(' • ');
        expect(line).toBe(
            'Розмір: 30х30 • Корінець: Стандартний • Тип оздоблення: Металева вставка • '
            + 'Варіант оздоблення: 90×50 золотий • Кількість сторінок: 50 • '
            + 'Калька перед першою сторінкою: Без кальки',
        );
    });
});
