import { describe, expect, it } from 'vitest';
import { matchCustomerName, normaliseName, phoneTail, shouldLinkOrder } from '@/lib/customers/name-match';

/**
 * Зіставлення імені в картці з іменем у замовленні.
 *
 * Усі пари нижче СПРАВЖНІ, зняті з бази 14.09.2026 — це гостьові замовлення,
 * пошта яких збігається з наявним акаунтом. Вигаданих прикладів тут немає
 * навмисно: саме реальні дані показали, що перша версія правила помилялася в
 * обидва боки, а перша версія цього тесту — теж, бо я записав у «та сама
 * людина» зменшувальні форми, які за рішенням Діани мають іти на перевірку.
 *
 * Дорожча помилка — прив'язати чуже замовлення. Тому блок «на перевірку»
 * важливіший за блок «прив'язати»: зайва хвилина менеджера дешевша за чужі
 * покупки в кабінеті.
 *
 * На всьому наборі з 50 різних пар правило дає 16 прив'язок і 34 перевірки,
 * і серед прив'язок немає жодної хибної.
 */

describe('normaliseName', () => {
    it('зводить російське і українське написання одного імені', () => {
        expect(normaliseName('Мария Литвин')).toEqual(normaliseName('Марія  Літвін '));
        expect(normaliseName('Диана Шрамко')).toEqual(normaliseName('Діана Шрамко'));
        expect(normaliseName('Виктория Сулакова')).toEqual(normaliseName('Вікторія Сулакова'));
    });

    it('зводить латиницю з кирилицею', () => {
        expect(normaliseName('Anastasia Kovalenko')).toEqual(normaliseName('Анастасія  Коваленко '));
        expect(normaliseName('Ruslana Buchynska')).toEqual(['ruslana', 'buchinska']);
    });

    it('прибирає апострофи, не розриваючи слово', () => {
        expect(normaliseName('Гловʼяк')).toEqual(['hlovak']);
        expect(normaliseName("Дар'я")).toEqual(['dara']);
    });

    it('викидає слова коротші за три літери — ініціали не доказ', () => {
        expect(normaliseName('К K')).toEqual([]);
        expect(normaliseName('Ліза С.')).toEqual(['liza']);
    });

    it('не падає на порожньому і нерядковому', () => {
        expect(normaliseName('')).toEqual([]);
        expect(normaliseName(null)).toEqual([]);
        expect(normaliseName(undefined)).toEqual([]);
        expect(normaliseName(42)).toEqual([]);
    });
});

/**
 * Прив'язуємо: та сама людина, записана по-різному.
 *
 * Кожен рядок звірений очима. Якщо тут почне з'являтися 'review', менеджер
 * потоне в ручній роботі і перестане її робити взагалі.
 */
describe('matchCustomerName — прив’язуємо', () => {
    it.each([
        ['анна витковская', 'Вітковська Анна'],
        ['Anastasia Kovalenko', 'Анастасія  Коваленко '],
        ['Anasnasiia Pushkar', 'Анастасія Пушкар'],
        ['Anastasya Skrypka', 'Анастасія Скрипка'],
        ['Ruslana Buchynska', 'Бучинська Руслана Василівна'],
        ['Людмила Горулько', 'Горулько Людмила Юріївна'],
        ['Марія Кравченко', 'Кравченко Марія Юріївна'],
        ['Мария Литвин', 'Марія  Літвін '],
        ['Диана Шрамко', 'Діана Шрамко'],
        ['Виктория Сулакова', 'Вікторія Сулакова'],
        ['Оксана Михайленко', 'Оксана Михайленко'],
    ])('%s ↔ %s', (card, order) => {
        expect(matchCustomerName(card, order).verdict).toBe('match');
    });

    /** В картці лише ім'я — порівнювати більше нічим, одного збігу досить. */
    it.each([
        ['Дарія', 'Фтемова Дарія Андріївна'],
        ['Мария', 'Квасова Марія'],
    ])('одне слово в картці: %s ↔ %s', (card, order) => {
        expect(matchCustomerName(card, order).verdict).toBe('match');
    });
});

/**
 * На перевірку: різні люди на спільній пошті.
 *
 * Кожен рядок тут пройшов би автоматично за наївним правилом «різна абетка
 * означає транслітерацію». «Julia Savkiv» проти «Савків Наталія» —
 * найважливіший: прізвище збігається, ім'я ні, і саме через нього потрібні ДВА
 * збіги, а не один.
 */
describe('matchCustomerName — різні люди, спільна пошта', () => {
    it.each([
        ['Svitlana Krasnova', 'Ірина Байдакова'],
        ['Olena Talailo', 'Марков Сергій'],
        ['Alyona Boguslavskaya', 'Олена Івченко'],
        ['Julia Savkiv', 'Савків Наталія'],
        ['Даніела Гловʼяк', 'Хабʼюк Наталія Василівна'],
        ['Ліза Сорока', 'Єлизавета Рудчик'],
    ])('%s ↔ %s', (card, order) => {
        expect(matchCustomerName(card, order).verdict).toBe('review');
    });
});

/**
 * На перевірку: зменшувальні форми.
 *
 * Списку зменшувальних у правилі немає навмисно (Діана, 14.09.2026): його
 * довелося б вічно доповнювати, а перша ж пропущена пара дала б або хибну
 * прив'язку, або незрозумілий виняток. Тест закріплює саме таку поведінку, щоб
 * ніхто не «полагодив» її списком мовчки.
 */
describe('matchCustomerName — зменшувальні йдуть на перевірку', () => {
    it.each([
        ['саша', 'Олександра Карак'],
        ['Саша Кришталь', 'Кришталь Олександра'],
        ['Катя Лабай', 'Катерина  Лабай'],
        ['Катерина Івашина', 'Катя Івашина'],
        ['Таня Вознюк', 'Тетяна Вознюк'],
        ['Татьяна', 'Тетяна Павлюк'],
        ['Іра Бурбило', 'Бурбило Ірина'],
        ['Даша Феер', 'Дарʼя Феєр '],
        ['Olya Serkez', 'Ольга Серкез'],
        ['Slavik Surminskiy', 'Вячеслав Сурмінський'],
    ])('%s ↔ %s', (card, order) => {
        expect(matchCustomerName(card, order).verdict).toBe('review');
    });
});

/**
 * На перевірку: одне слово збіглося, друге ні.
 *
 * Тут правило свідомо обережніше за людину. «Софія Шалишич» і «Софія Галишич»
 * майже напевно одна людина з одруківкою в прізвищі, а «Марьяна Ткаченко» і
 * «Марьяна Бірюк» можуть бути і зміною прізвища, і двома різними людьми. Ціна
 * помилки несиметрична, тож обидва випадки дивиться менеджер.
 */
describe('matchCustomerName — половина збігу', () => {
    it.each([
        ['Софія Шалишич', 'Софія Галишич'],
        ['Марьяна Ткаченко', 'Марьяна Бірюк'],
        ['Юля Кондратюк', 'Юдія Кондратюк'],
        ['Зоряна Нивчик', 'Царик Зоряна Миколаївна'],
    ])('%s ↔ %s', (card, order) => {
        expect(matchCustomerName(card, order).verdict).toBe('review');
    });
});

describe('matchCustomerName — нема чого порівнювати', () => {
    it.each([
        ['К K', 'Дрозд Катерина Петрівна'],
        ['iqd', 'Данііл Ісакин'],
    ])('сміття в картці: %s ↔ %s', (card, order) => {
        expect(matchCustomerName(card, order).verdict).toBe('review');
    });

    it('порожнє ім’я не прив’язується в жодну сторону', () => {
        expect(matchCustomerName('', 'Дрозд Катерина').verdict).toBe('review');
        expect(matchCustomerName('Дрозд Катерина', null).verdict).toBe('review');
        expect(matchCustomerName(null, null).verdict).toBe('review');
    });
});

describe('phoneTail', () => {
    it('зводить різні написання одного номера', () => {
        expect(phoneTail('+380 67 123 45 67')).toBe('671234567');
        expect(phoneTail('0671234567')).toBe('671234567');
        expect(phoneTail('380671234567')).toBe('671234567');
    });

    it('закороткий номер не порівнюємо', () => {
        expect(phoneTail('12345')).toBeNull();
        expect(phoneTail(null)).toBeNull();
    });
});

/**
 * Телефон може лише ПОСИЛИТИ обережність.
 *
 * Збіг імені при різних телефонах означає, що за поштою можуть бути двоє.
 * Зворотного впливу немає: різниця в телефоні ніколи не робить 'review' на
 * 'match'. На сьогодні спрацьовує майже ніколи — телефон заповнений у 12
 * карток із 1280, — але коштує нічого.
 */
describe('shouldLinkOrder', () => {
    it('імена збіглися і телефони збіглися — прив’язуємо', () => {
        expect(shouldLinkOrder({
            cardName: 'Ruslana Buchynska', orderName: 'Бучинська Руслана Василівна',
            cardPhone: '+380671234567', orderPhone: '0671234567',
        }).verdict).toBe('match');
    });

    it('імена збіглися, телефони різні — на перевірку', () => {
        expect(shouldLinkOrder({
            cardName: 'Ruslana Buchynska', orderName: 'Бучинська Руслана Василівна',
            cardPhone: '+380671234567', orderPhone: '+380509999999',
        }).verdict).toBe('review');
    });

    it('телефон є лише з одного боку — рішення за іменем', () => {
        expect(shouldLinkOrder({
            cardName: 'Ruslana Buchynska', orderName: 'Бучинська Руслана Василівна',
            cardPhone: null, orderPhone: '0671234567',
        }).verdict).toBe('match');
    });

    it('різних людей не рятує навіть однаковий телефон', () => {
        expect(shouldLinkOrder({
            cardName: 'Svitlana Krasnova', orderName: 'Ірина Байдакова',
            cardPhone: '0671234567', orderPhone: '0671234567',
        }).verdict).toBe('review');
    });
});
