-- Відгук знає, з якого він замовлення.
--
-- НАВІЩО. Правило «не просити відгук, якщо він уже є» перевірити було нічим:
-- reviews зберігав лише product_id, автора й текст, а звʼязку із замовленням не
-- мав зовсім. Через це крон прохань не міг відрізнити людину, яка вже написала,
-- від тієї, яка мовчить (Діана, 16.09.2026).
--
-- Без зовнішнього ключа свідомо, гоча 12 у CLAUDE.md: ключі на orders уже
-- множаться, а PostgREST на двох ключах до однієї таблиці відмовляє цілим
-- запитом. Тут потрібне саме значення, а не вбудовування.
alter table reviews add column if not exists order_id uuid;

create index if not exists reviews_order_id_idx on reviews (order_id) where order_id is not null;

comment on column reviews.order_id is 'Замовлення, з якого лишили відгук; порожнє для відгуків, доданих вручну';
