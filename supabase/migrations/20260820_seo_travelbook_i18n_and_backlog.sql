-- Застосовано до Supabase шістьма міграціями:
--   seo_travelbook_country_backlog
--   seo_travelbook_i18n_batch1 .. batch4
-- Повний SQL зберігається в історії міграцій Supabase; тут фіксуємо, що саме
-- змінилось і чому, бо самі стейтменти займають десятки кілобайт.
--
-- ── Що виправлено ───────────────────────────────────────────────────────────
--
-- landing_pages.translations на сімнадцяти країнових сторінках мала лише h1 і
-- не мала ні intro, ні faq для жодної локалі. Роут падає на українську, тому
-- /en, /pl, /ro і /de віддавали український текст під перекладеним заголовком.
-- Це шістдесят вісім URL у такому стані.
--
-- Тепер кожна з сімнадцяти країн має intro, faq і meta_title чотирма мовами.
-- meta_description окремо не заводимо: generateMetadata бере
-- meta_description || intro, а intro тепер локалізоване, тож сніпет теж.
--
-- Тексти написані під ринок, а не перекладені дослівно з української. Для SEO
-- це правильніше, бо кожна локаль ловить свої формулювання, а Google не вимагає
-- від перекладу буквальності. Відповіді у faq писались під конкретну країну,
-- щоб сімнадцять сторінок на чотирьох мовах не ділили один набір.
--
-- Дрібниця з першого проходу: у польському faq Грузії в слово "supra"
-- затесалася кирилична "а". Виправлено в batch3.
--
-- ── Черга країн ─────────────────────────────────────────────────────────────
--
-- Чотирнадцять наступних країн створені прямо в landing_pages з
-- is_active = false. Такий рядок повністю невидимий: getLanding фільтрує
-- is_active і віддає 404, sitemap і чіпи категорії його не беруть.
--
-- У кожного вже заповнені h1, meta_title, meta_description, product_slugs і
-- sort_order. Щоб випустити країну, лишається дописати intro та faq (українською
-- і чотирма локалями) і поставити is_active = true.
