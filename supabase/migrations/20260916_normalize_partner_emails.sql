-- Разова нормалізація пошти партнерів (Діана, 16.09.2026).
--
-- Пара до правки в lib/agency/create-partner.ts, яка з цього дня зберігає пошту
-- вже обрізаною і в нижньому регістрі. Ця міграція прибирає те, що встигло
-- лягти в базу до неї.
--
-- НАВІЩО, ЯКЩО БИТИХ РЯДКІВ ЗАРАЗ НУЛЬ. Саме тому й варто: поки їх нуль, дія
-- безпечна і перевіряється однією цифрою. Ціна помилки несиметрична — партнер
-- із пробілом у пошті не збігається з поштою своєї сесії, і `/uk/partner/
-- cabinet` каже йому «кабінет не знайдено», а форма відновлення відповідає
-- «надіслали» і не надсилає нічого, бо її відповідь однакова для всіх. Тобто
-- зламане мовчить із двох боків одразу.
--
-- ДУБЛІВ НЕ БУДЕ, і це перевірено, а не припущено: на момент міграції жоден
-- рядок не змінюється взагалі (0 із 3), тож злити дві різні агенції в одну
-- нормалізація не може. Умова у WHERE лишає дію ідемпотентною — повторний
-- прогін не чіпає нічого.

update public.agency_partners
   set email = btrim(lower(email))
 where email is not null
   and email <> btrim(lower(email));
