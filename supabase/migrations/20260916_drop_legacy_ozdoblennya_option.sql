-- Прибрати групу опцій «Оздоблення» з трьох фотокниг.
--
-- ЩО САМЕ ВИДАЛЯЄТЬСЯ. Одна група опцій із products.options у трьох товарів —
-- photobook-fabric, photobook-leatherette, photobook-velour. Групи «Варіант
-- акрилу» і «Варіант фотовставки» НЕ чіпаються: вони єдине джерело розмірів
-- акрилу й фотовставки на картці товару, і про їхню долю є окрема задача
-- (issue #70, зведення двох джерел розмірів в одне).
--
-- ЧОМУ ЦЕ ЗАЙВЕ. Це залишок старого селекта. Оздоблення вже пів року
-- обирається пігулками, які пишуть у позицію ключ «Тип оздоблення» і беруть
-- список із коду (VELOUR_OZDOBLENNYA), а не з products.options. Стару групу
-- обидва інтерфейси ховають ЗАВЖДИ: на картці товару вона в жорсткому списку
-- пропуску (ProductClient), у модалці «з дизайнером» ховається для м'яких
-- обкладинок, а для друкованої обкладинки її в даних і немає.
--
-- ЧОМУ ЦЕ НЕ ПРОСТО СМІТТЯ. Модалка «з дизайнером» засіває конфіг ПЕРШИМ
-- значенням кожної групи products.options. Перше значення тут — «Без
-- оздоблення», і воно їхало в замовлення поруч зі справжнім вибором. Так у
-- восьми позиціях з'явилася пара, де «Оздоблення» каже «Без оздоблення», а
-- «Тип оздоблення» — «Металева вставка». Два друкарські маршрути ухвалювали
-- за цим сусідом рішення про файли: findMonoCoverItem (чи робити макет на
-- гравіювання) і generate-cover-bw (чи вирізати фото для фотовставки).
-- Читачів уже навчено питати «Тип оздоблення» першим, але краще не
-- створювати того, що доводиться прибирати.
--
-- ЧОМУ БЕЗПЕЧНО. Ціни всіх значень у групі — нулі, тож підсумок у модалці не
-- зрушиться (вона додає match.price по кожній обраній опції). У замовленнях за
-- всю історію ключ «Оздоблення» є в одинадцяти позиціях, і лише в одній він
-- стоїть без «Тип оздоблення» — зі значенням «Без оздоблення». Тобто жодна
-- позиція не втрачає змісту.
--
-- ЧОМУ WITH ORDINALITY. Без явного порядку jsonb_agg пересортує решту груп, і
-- на картці товару розмір міг би поїхати нижче за кальку. Умова @> робить
-- міграцію ідемпотентною.
--
-- ЯК ВІДКОТИТИ. Значення трьох груп різняться між товарами, і це саме по собі
-- показово: у тканини й велюру значення — латинські слаги, у шкірзамінника —
-- українські підписи, а «Флекс» у шкірзамінника має значення «Друк кольором».
-- Саме така різнобій і робила старий ключ ненадійним. Повний вміст на момент
-- видалення:
--
--   photobook-fabric   → none | acryl | photovstavka | flex
--   photobook-velour   → none | acryl | photovstavka | metal | flex | graviruvannya
--   photobook-leatherette → «Без оздоблення» | «Акрил» | «Фотовставка» |
--                           «Металева вставка» | «Друк кольором»
--
--   Усі з price = 0, type = 'select', required = false
--   (у velour ключа required немає взагалі).
--
-- Щоб повернути, додати групу назад через jsonb_insert у потрібну позицію
-- масиву — вона стояла четвертою, між «Калька перед першою сторінкою» і
-- «Варіант акрилу».

update products p
set options = (
        select coalesce(jsonb_agg(g order by ord), '[]'::jsonb)
        from jsonb_array_elements(p.options) with ordinality as t(g, ord)
        where g->>'name' <> 'Оздоблення'
    ),
    updated_at = now()
where p.slug in ('photobook-fabric', 'photobook-leatherette', 'photobook-velour')
  and p.options @> '[{"name": "Оздоблення"}]';
