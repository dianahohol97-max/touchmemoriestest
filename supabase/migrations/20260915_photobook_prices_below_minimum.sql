-- Прибрати ціни на комбінації, яких не існує.
--
-- ЩО САМЕ. Мінімальна кількість розворотів у фотокниги залежить від розміру:
-- 20×20 від 6, 25×25 від 8, 20×30 і 30×20 від 10, 30×30 від 16 (Діана,
-- 15.09.2026, підтверджено для всіх обкладинок, друкованої теж). Картка
-- товару це правило застосовує давно, і три преміальні обкладинки —
-- тканина, шкірзам, велюр — мають у таблиці цін рівно дозволені пари: по
-- 105 рядків. А в друкованої лежало 115: десять рядків на комбінації нижче
-- мінімуму.
--
-- ЧОМУ ЦЕ БУЛА ДОБИВКА, А НЕ ЦІНИ. У кожному зайвому рядку ціна просто
-- скопійована з першого справжнього тарифу свого розміру: 20×30 на 6 і 8
-- коштували 890 ₴ — стільки ж, скільки 20×30 на 10; 30×30 на 6, 8, 10, 12 і
-- 14 коштували 1255 ₴ — стільки ж, скільки 30×30 на 16. Тобто таблицю колись
-- добили до повної сітки, повторивши перший тариф.
--
-- ЩО ЦЕ КОШТУВАЛО. Замовити такі комбінації клієнт не міг — картка їх не
-- показує, і в базі немає жодного такого замовлення за весь час. Але з цих
-- рядків будувався перелік варіантів для звірки каталогу з KeyCRM, і через
-- них у мапі зʼявилося 18 зіставлень на товари, яких не існує, а ще чотири
-- комбінації мало не поїхали менеджерці списком «завести в CRM».
--
-- БЕЗПЕКА. Жодної справжньої ціни не зачіпає: усі десять рядків нижче
-- мінімуму, який картка й так не пропускає. Видалене записується в
-- photobook_price_changes (new_price = null), щоб зміна лишила слід.

with doomed as (
    select p.id, ct.name as cover, s.name as size, p.page_count, p.base_price
    from photobook_prices p
    join cover_types ct on ct.id = p.cover_type_id
    join photobook_sizes s on s.id = p.size_id
    where ct.name = 'Друкована'
      and (  (s.name = '20×20' and p.page_count < 6)
          or (s.name = '25×25' and p.page_count < 8)
          or (s.name = '20×30' and p.page_count < 10)
          or (s.name = '30×20' and p.page_count < 10)
          or (s.name = '30×30' and p.page_count < 16))
),
logged as (
    insert into photobook_price_changes (cover_type, size, page_count, old_price, new_price, source)
    select cover, size, page_count, base_price, null, 'cleanup-below-minimum' from doomed
    returning 1
)
delete from photobook_prices where id in (select id from doomed);
