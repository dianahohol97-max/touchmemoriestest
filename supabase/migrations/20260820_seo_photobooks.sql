-- Фотокниги: чотири сторінки замість чотирьох копій однієї.
--
-- Застосовано до Supabase двома міграціями:
--   seo_photobooks_printed_fabric
--   seo_photobooks_leatherette_velour
-- Повний SQL зберігається в історії міграцій Supabase; тут фіксуємо, що саме
-- змінилось і чому, бо самі стейтменти займають десятки кілобайт.
--
-- ── Що було не так ──────────────────────────────────────────────────────────
--
-- Чотири фотокниги — це флагман каталогу, і всі чотири сторінки мали
-- ідентичний перший абзац, слово в слово:
--
--   «Ми працюємо з матовим Fujicolor Crystal Archive — папером із гарантією
--    понад 100 років. Сторінки склеєні без прошарку, розворот розкривається
--    на 180° повністю плоско.»
--
-- Далі йшло одне речення про матеріал обкладинки і однакова кінцівка про
-- ручну збірку на картоні 2 мм. Опис у кожної був близько 290 символів, з
-- яких приблизно 220 збігалися дослівно. Таблиця характеристик збігалася на
-- всі сто відсотків: шість однакових рядків, жодного слова про обкладинку,
-- тобто саме про те, чим ці чотири товари відрізняються. Три з чотирьох
-- meta_title казали «від 1500 грн».
--
-- Для пошуку це чотири сторінки, які конкурують між собою за один і той самий
-- запит «фотокнига», і жодна не має власного. Google обирає одну з них сам, і
-- це не обовʼязково та, яка продає найкраще.
--
-- ── Що дає різницю ──────────────────────────────────────────────────────────
--
-- Реальні відмінності лежали в cover_types/cover_colors і в options, їх просто
-- ніде не було в тексті:
--
--   шкірзамінник   25 активних кольорів, гладкий, витирається
--   велюр          15 кольорів, і єдиний матеріал, на якому робимо гравіювання
--                  (у нього одного в options «Оздоблення» є «Гравірування»)
--   тканина        8 приглушених кольорів, фактура переплетення
--   друкована      фото друкується прямо на палітурці, і ціна від 600 ₴
--
-- Кожна сторінка тепер побудована навколо своєї відмінності, порівнює себе з
-- трьома іншими своїми словами і веде на них посиланням. Це прибирає
-- канібалізацію і водночас робить перелінковку всередині групи.
--
-- ── Що змінено на кожному товарі ────────────────────────────────────────────
--
--   description        новий текст 2200–3300 символів українською, з h2/h3 і
--                      блоком частих питань під featured snippets
--   translations       description, meta_title і meta_description для en, pl,
--                      ro, de; тексти писані під ринок, не перекладені дослівно
--   meta_title         свій у кожного, без спільного «від 1500 грн»
--   meta_description   свій, з числом кольорів або з ціною
--   specs              додано сьомий рядок «Обкладинка» з матеріалом і
--                      кількістю кольорів, пʼятьма мовами
--   sku                TM-PB-PRINT, TM-PB-FABRIC, TM-PB-LEATHER, TM-PB-VELOUR
--   status             photobook-fabric і photobook-leatherette мали 'draft'
--                      при is_active = true, тобто розбіжність між двома
--                      прапорцями видимості; обидва вирівняно на 'active'
--
-- ── Дрібниця, яку варто памʼятати ───────────────────────────────────────────
--
-- У польському тексті обох нових сторінок у слово «weluru» затесалася
-- кирилична «у». Та сама помилка, що була в грузинському faq зі словом
-- «supra». Виправлено одразу; перевірка на майбутнє:
--
--   SELECT p.slug, k FROM products p, jsonb_each(p.translations) AS e(k,v)
--   WHERE k IN ('en','pl','ro','de') AND v->>'description' ~ '[а-яА-ЯіїєґІЇЄҐ]';
--
-- ── Перевірка після застосування ────────────────────────────────────────────
--
-- Чотири різні перші абзаци, чотири різні meta_title, у кожного сьомий рядок
-- характеристик «Обкладинка», у кожного від двох до трьох посилань на сусідні
-- фотокниги, жодної кирилиці в чотирьох неукраїнських локалях.
--
-- ── Що лишилось поза цією міграцією ─────────────────────────────────────────
--
-- У фотокниг нуль відгуків, тому зірочок у видачі не буде навіть з ідеальним
-- текстом. Це не правиться міграцією і потребує окремого рішення Діани.
