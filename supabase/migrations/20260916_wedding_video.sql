-- Відео на весільній сторінці (Діана, 16.09.2026).
--
-- ЧОМУ ЗАВАНТАЖЕННЯ ПЕРЕЇХАЛО З НАШОГО РОУТА ПРЯМО В БАКЕТ. Функція на Vercel
-- приймає тіло запиту розміром до 4,5 МБ — це межа платформи, і обійти її
-- налаштуванням не можна. Тридцять секунд відео з iPhone важать понад сто
-- мегабайтів, тобто через наш роут вони не пройшли б ніколи. Тепер сервер
-- видає підписане посилання на ОДИН конкретний обʼєкт, клієнт кладе файл прямо
-- в бакет, а сервер після того перевіряє, що там справді лежить, і лише тоді
-- створює рядок. Прямого запису в бакет клієнт так і не отримав: посилання
-- одноразове, на єдиний шлях, і видає його наш код після перевірки типу й
-- розміру.
--
-- Побічно це полагодило приховану ваду й для фото. Стиснення на клієнті може не
-- спрацювати — бракує памʼяті, дивний профіль, старий телефон, — і тоді летів
-- оригінал на вісім мегабайтів. Він теж не проходив крізь ту саму межу в 4,5 МБ,
-- і гість бачив помилку, причини якої в наших журналах не було взагалі, бо
-- запит помирав до нашого коду.

alter table public.wedding_photos
  add column if not exists mime_type text,
  add column if not exists poster_path text,
  add column if not exists duration_seconds numeric;

-- Наявні рядки — це знімки, завантажені до появи відео.
update public.wedding_photos
   set mime_type = 'image/jpeg'
 where mime_type is null;

alter table public.wedding_photos
  alter column mime_type set not null;

-- Обкладинка потрібна саме відео і саме через сітку галереї.
--
-- Без неї плитка або лишається чорним прямокутником, або мусить тягнути сам
-- ролик заради першого кадру. Півсотні таких плиток на телефоні в поганій
-- мережі — це десятки мегабайтів заради картинок, які гість, можливо, навіть не
-- відкриє. Обкладинку знімає браузер того, хто завантажує, і важить вона
-- десятки кілобайтів.
comment on column public.wedding_photos.poster_path is
  'Шлях до кадру-обкладинки в тому ж бакеті. Заповнений лише для відео.';

comment on column public.wedding_photos.mime_type is
  'Тип файлу. Галерея за ним вирішує, показувати картинку чи програвач.';

-- Бакет приймає відео і піднімає межу до 200 МБ.
--
-- 200 МБ — це приблизно три хвилини 1080p або сорок секунд 4K. Більше для
-- весільного вітання не потрібно, а менше відрізало б половину роликів з
-- сучасних телефонів. Стиснути відео на клієнті, як ми робимо з фото, не
-- вийде: браузер не вміє перекодовувати відео ані швидко, ані надійно.
--
-- image/heic у списку немає навмисно: HEIC перетворюється на JPEG ще в
-- браузері гостя, тож у бакет він доходить уже картинкою.
update storage.buckets
   set file_size_limit = 209715200,
       allowed_mime_types = array[
         'image/jpeg', 'image/png', 'image/webp',
         'video/mp4', 'video/quicktime', 'video/webm'
       ]
 where id = 'wedding-photos';

-- Книга побажань — ТІЛЬКИ ВІДЕО (Діана, 16.09.2026).
--
-- Побажання це не окрема сутність, а той самий запис гостя з позначкою. Носій
-- у нього той самий, що й у галереї, тож окрема таблиця означала б двічі
-- писати завантаження, двічі пагінацію і двічі прибирання за подією.
--
-- ЧОМУ ПРАПОРЕЦЬ, А НЕ «ВСЕ ВІДЕО — ЦЕ ПОБАЖАННЯ». Гість цілком може скинути
-- ролик із танцполу просто в галерею, і той не має потрапляти в книгу
-- побажань. Відеолистівку людина записує навмисно і натискає для цього окрему
-- кнопку — саме цей намір і зберігає прапорець.
alter table public.wedding_photos
  add column if not exists is_wish boolean not null default false;

-- Побажання буває лише відео: фото з підписом як формат прибрали свідомо.
-- Перевірка стоїть у базі, щоб помилка в коді не завела в книгу картинку.
alter table public.wedding_photos
  drop constraint if exists wedding_photos_wish_is_video;
alter table public.wedding_photos
  add constraint wedding_photos_wish_is_video
  check (not is_wish or mime_type like 'video/%');

-- Книга читається окремим запитом і своїм порядком, тож їй потрібен свій
-- індекс. Частковий, бо побажань завжди буде на порядок менше за знімки.
create index if not exists wedding_photos_event_wish_idx
  on public.wedding_photos (event_id, created_at desc)
  where is_wish;
