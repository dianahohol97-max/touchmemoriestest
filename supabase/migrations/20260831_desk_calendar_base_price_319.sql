-- Настільний фотокалендар: базова ціна 269 → 319 ₴.
--
-- Розбіжність між карткою товару і кошиком. У products.price лежало 269, а
-- модифікатори опції «Комплектація» — 0 за варіант з мольбертом і -50 без
-- нього. Тобто каталог рахував 269 ₴ з мольбертом і 219 ₴ без. Водночас
-- підписи самих варіантів кажуть «(319 грн)» і «(269 грн)», і рівно ці числа
-- рахує конструктор (DeskCalendarConstructor: 319 + (hasStand ? 0 : -50)).
--
-- Клієнтка бачила на картці 269 ₴, а в кошику отримувала 319 ₴.
--
-- Правильна база — 319 (рішення Diana, 2026-08-31): конструктор рахує вірно,
-- застаріле саме поле price. Після цієї зміни всі три джерела збігаються:
--   з мольбертом  → 319 + 0   = 319 ₴  (як у підписі варіанта)
--   без мольберта → 319 + (-50) = 269 ₴  (як у підписі варіанта)
--
-- Опції не чіпаємо — вони вже правильні, змінюється лише база.

update products
set price = 319.00,
    updated_at = now()
where slug = 'desk-calendar-2026'
  and price = 269.00;
