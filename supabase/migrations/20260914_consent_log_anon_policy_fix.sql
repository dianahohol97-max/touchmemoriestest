-- ВИПРАВЛЕННЯ, а не фіксація стану.
--
-- Попередній файл (20260914_consent_log_baseline.sql) переніс consent_log у
-- репозиторій як є — разом із суперечністю, яку я там свідомо не чіпала і
-- позначила коментарем. Тут вона виправляється, і саме тому окремим файлом:
-- зліпок має лишатися зліпком, щоб через півроку було видно, що в базі було
-- насправді, а що ми змінили руками.
--
-- У ЧОМУ БУЛА СУПЕРЕЧНІСТЬ.
--
-- Політика anon_insert_cookie_consent дозволяла гостю вставляти рядки лише з
-- consent_type у списку 'cookies_accepted' / 'cookies_partial' /
-- 'cookies_rejected' — це НАЗВИ ДІЙ. А CHECK самої таблиці дозволяє тільки
-- НАЗВИ КАТЕГОРІЙ: essential, analytics, marketing, functional, terms,
-- privacy. Два правила не перетинаються ніде, тож жодна вставка від
-- анонімного відвідувача не могла задовольнити обидва одночасно: політика
-- пропускала рівно ті значення, які обмеження забороняло.
--
-- Практичних наслідків не було, бо в consent_log пише тільки сервер сервісним
-- ключем, а він RLS не питає. Але пастка лишалася: перший, хто спробував би
-- записати згоду прямо з браузера, отримав би відмову, у якій ніщо не вказує
-- на причину.
--
-- ЩО ЗМІНЮЄТЬСЯ.
--
-- Політика тепер дозволяє рівно чотири категорії банера cookie — ті самі, що
-- й CHECK таблиці, і ті самі, що шле lib/consent/log-entries.ts. 'terms' і
-- 'privacy' до цього списку НЕ входять: вони приходять із реєстрації, де
-- людина вже має сесію, і для них діє окрема політика
-- authenticated_insert_own_consent.
--
-- Умова customer_id is null лишається як була: гість за визначенням не має
-- рядка клієнта, і без неї анонім міг би приписати згоду чужому акаунту.
--
-- Альтернатива, яку ми не обрали: прибрати політику зовсім. Наші маршрути її
-- не потребують — усі пишуть сервісним ключем. Але тоді пряма вставка з
-- браузера стала б неможливою назавжди, а задум був саме в тому, щоб банер міг
-- писати згоду й без сервера. Лишаємо можливість, приводячи її до працездатного
-- вигляду (Diana, 14.09.2026).

drop policy if exists anon_insert_cookie_consent on public.consent_log;

create policy anon_insert_cookie_consent on public.consent_log
    for insert to anon
    with check (
        customer_id is null
        and consent_type = any (array['essential', 'analytics', 'marketing', 'functional'])
    );

comment on policy anon_insert_cookie_consent on public.consent_log is
    'Гість може записати згоду лише за категоріями банера cookie і лише без '
    'привʼязки до акаунта. Список збігається з CHECK таблиці — до 14.09.2026 '
    'вони суперечили одне одному і жодна анонімна вставка не проходила.';
