-- План менеджера, з яким звіряється бонус за виконання.
--
-- Стовпець уже описаний у міграції salary_qc/20260313010000_salary_qc_module.sql,
-- але в бойову базу той ALTER не доїхав: таблиці змін і помилок створилися, а
-- staff лишився без цього поля (перевірено 15.09.2026 через information_schema).
-- Код читав порожнечу, `staff.manager_plan_target || 0` давав план нуль, умова
-- «обіг не менший за план» ставала завжди істинною, і тисяча гривень бонусу
-- нараховувалася кожному менеджеру незалежно від результату.
--
-- DEFAULT тут навмисно НЕМАЄ, на відміну від тієї міграції. Нуль за
-- замовчуванням — це і є перевернута логіка: план, якого ніхто не ставив,
-- виглядав би виконаним. Порожнє значення означає «плану немає, бонус не
-- нараховується», і заповнює його Діана руками, коли вирішить цифру.
ALTER TABLE public.staff ADD COLUMN IF NOT EXISTS manager_plan_target NUMERIC;

COMMENT ON COLUMN public.staff.manager_plan_target IS
    'Місячний план обігу менеджера, грн. Порожньо означає, що плану немає і бонус за план не нараховується. Обіг рахується отриманими грошима за датою замовлення — lib/orders/revenue-period.ts.';
