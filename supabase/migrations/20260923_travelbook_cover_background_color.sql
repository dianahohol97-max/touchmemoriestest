-- Колір тла готової обкладинки тревелбука живе в каталозі, а не вгадується.
--
-- До цієї міграції колонки не було взагалі, і колір задньої обкладинки брався
-- з двох однаково поганих джерел. Конструктор рахував його з картинки:
-- малював її в канву 48×48 і усереднював зовнішнє кільце завширшки пʼять
-- пікселів, тобто більш ніж третину площі. У наших дизайнів там декоративна
-- рамка, тож середнє виходило між тлом і орнаментом. «Аргентина» так дістала
-- бурий #b27467 при рожевому тлі, і однаковий він у всіх трьох макетах з нею,
-- бо клієнтка його не обирала. Другий шлях був ще прямолінійніший: вибір
-- обкладинки на кроці конфігурації підставляв зашитий у код сірий #e5e7eb —
-- одинадцять макетів у базі мають рівно його.
--
-- Колонка порожня за замовчуванням і це свідомо: порожнє значення означає
-- «кольору ще ніхто не задав», і конструктор тоді рахує підказку сам. Коли
-- колір заданий, він виграє завжди.
--
-- Колір у вже збережених макетах ця міграція НЕ чіпає: cover_data кожного
-- проєкту лишається таким, яким його погодила клієнтка.
ALTER TABLE public.travelbook_covers
  ADD COLUMN IF NOT EXISTS background_color text;

COMMENT ON COLUMN public.travelbook_covers.background_color IS
  'Колір тла обкладинки у форматі #rrggbb. Задається оком в адмінці; порожнє значення означає, що конструктор порахує підказку сам.';
