-- Фотожурнал з твердою обкладинкою: базова ціна 825 → 675 ₴
--
-- Проблема: замовлення TM-001202 (12 сторінок) провелося на 825 ₴ замість 675 ₴.
-- Те саме було з кожною конфігурацією цього товару — рівно +150 ₴.
--
-- Причина: товар сконфігурований за схемою «базова ціна + надбавка за опцію».
-- Надбавки в options → «Кількість сторінок» рахуються від 12-сторінкового
-- анкера 675 ₴ (16 → +150, 20 → +300, 24 → +450 і далі кроком 75 ₴ на кожні
-- дві сторінки), а products.price лишився 825 ₴ — ціна 16 сторінок. Тобто
-- анкер зсунули на один щабель уперед, а базу не опустили. Твінний товар
-- Travel Book, у якого та сама шкала цін, має правильні 675 ₴.
--
-- Виправлення: опустити базу до 675 ₴. Надбавки не чіпаємо — вони всі вірні,
-- і після зміни бази кожен щабель сходиться з lib/products.ts
-- PHOTO_JOURNAL_HARD.prices до гривні: 12 → 675, 16 → 825, 20 → 975, 24 → 1125,
-- 28 → 1275, 32 → 1425, 36 → 1575, 40 → 1725, 44 → 1875, 48 → 2025, 52 → 2150,
-- 60 → 2350, 72 → 2650, 80 → 2900.
--
-- Перевірка: сторінка товару /catalog/fotozhurnal-tverd-obkladynka на 12
-- сторінках має показати 675 ₴, і та сама сума має прийти в кошик.

update products
   set price = 675.00,
       updated_at = now()
 where slug = 'fotozhurnal-tverd-obkladynka'
   and price = 825.00;
