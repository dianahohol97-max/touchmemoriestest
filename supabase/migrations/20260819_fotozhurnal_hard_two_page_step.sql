-- не отримає. Це та сама історія, що вже сталась із фотокнигами (TM-001195,
-- TM-001185, TM-001197 і ще кілька з березня).
--
-- Cause: Travel Book отримав кожну парну кількість сторінок кроком 75 грн,
-- а журнал з ідентичною шкалою лишився зі старим списком.
--
-- Fix: тарифи журналу тепер повторюють Travel Book один в один — кожна парна
-- кількість від 12 до 80. Крок 75 грн тримається від 12 до 48; вище 48 ціни
-- йдуть за анкерами Діани кроком 50 грн, це свідома знижка на обсяг, і вона
-- збережена до гривні. Надбавки відраховані від бази 675 грн, тому жодна вже
-- наявна ціна не змінюється: 12 стор. лишаються 675, 16 стор. — 825, 20 — 975.
-- У коді ті самі числа беруться з TRAVEL_BOOK.prices (lib/products.ts), тому
