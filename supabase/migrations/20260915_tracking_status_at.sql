-- Час ОСТАННЬОЇ ЗМІНИ статусу посилки.
--
-- Навіщо: зведення про застряглі посилки має сказати менеджеру, скільки днів
-- посилка лежить на відділенні. Дата замовлення на це питання не відповідає —
-- замовлення від третього липня могло приїхати на відділення вчора, і назвати
-- його застряглим на 74 дні означало б збрехати. Окремої історії статусів
-- посилки в нас немає: order_history пише про оплату, статус замовлення і
-- синхронізацію з CRM, але не про трекінг.
--
-- Колонку заповнює крон /api/nova-poshta/sync-tracking і тільки тоді, коли
-- статус СПРАВДІ змінився. Оновлювати її щопрогону не можна: крон ходить
-- щодня, і тоді кожна посилка вічно мала б нуль днів у статусі.
--
-- Жодного зовнішнього ключа тут немає навмисно — гоча 12 у CLAUDE.md про те,
-- як другий ключ на ту саму таблицю кладе PostgREST-запити цілком.
alter table public.orders
    add column if not exists tracking_status_at timestamptz;

comment on column public.orders.tracking_status_at is
    'Коли трекінг-статус змінився востаннє. Пише крон Нової Пошти при зміні статусу; NULL означає, що зміни ще не бачили.';
