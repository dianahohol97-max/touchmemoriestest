-- Полароїд: опис більше не обіцяє вибір покриття.
--
-- Навіщо. У картці стояло «Матовий або глянцевий папір (на вибір)», а опції
-- «Покриття» в цього товару немає взагалі: `polaroid-print` несе тільки
-- «Формат». Полароїд матовий за замовчуванням, і це свідоме рішення Діани
-- (гоча 10 у CLAUDE.md), а не забута опція. Опис, який пропонує вибір,
-- якого форма замовлення не дає, породжує питання в дірект і замовлення
-- з коментарем «хочу глянець», на який ми все одно відповімо відмовою.
--
-- Запит написаний через replace(), а не через новий текст цілком: опис
-- Діана редагує сама, і переписування всієї колонки затерло б її правки,
-- зроблені після цієї міграції. Повторний запуск нічого не змінює, бо
-- після першого проходу шуканих рядків у тексті вже немає.
update public.products
set description = replace(
      replace(
        description,
        'Матовий або глянцевий папір Fuji, фотохімічний друк.',
        'Матовий папір Fuji, фотохімічний друк.'
      ),
      '<li>Матовий або глянцевий папір (на вибір)</li>',
      '<li>Папір матовий, глянцевого варіанту немає</li>'
    )
where slug = 'polaroid-print';

