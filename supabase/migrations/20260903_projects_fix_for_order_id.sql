-- Копія макета, зроблена співробітником для виправлення конкретного замовлення.
--
-- НАВІЩО. Дизайнер тисне «Макет → мої чернетки», отримує копію макета клієнта
-- у власних чернетках і редагує її вільно. Досі зв'язок копії із замовленням
-- існував лише в назві — «TM-001257 — переекспорт», — і з цього виходили дві
-- біди.
--
-- Перша: конструктор про замовлення нічого не знав, тож кнопка «Зберегти та
-- замовити» робила те саме, що завжди, і виправлення чужого макета лягало в
-- кошик дизайнера як нова покупка на 920 ₴. У кошику oksanamatsopa так
-- зібралося три позиції на 3010 ₴, з них дві однакові.
--
-- Друга: список «Ваші виправлені макети» в картці замовлення шукав чернетки за
-- збігом назви. Перейменована чернетка з нього зникала, а чужа з подібною
-- назвою могла потрапити.
--
-- Колонка nullable і ні на що не впливає для звичайних макетів клієнтів.
-- ON DELETE SET NULL: видалення замовлення не має тягти за собою чернетку
-- дизайнера, вона просто перестає бути виправленням.
alter table public.projects
  add column if not exists fix_for_order_id uuid
  references public.orders(id) on delete set null;

comment on column public.projects.fix_for_order_id is
  'Замовлення, для якого цю чернетку створено як виправлення (кнопка «Макет → мої чернетки»). NULL для звичайних макетів клієнтів.';

-- Пошук чернеток одного замовлення. Часткий індекс, бо таких рядків одиниці
-- на тлі всіх макетів.
create index if not exists projects_fix_for_order_id_idx
  on public.projects (fix_for_order_id)
  where fix_for_order_id is not null;
