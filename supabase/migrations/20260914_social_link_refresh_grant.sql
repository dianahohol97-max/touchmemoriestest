--
-- Матчер link_social_conversations був задуманий як разовий прохід, і права на
-- нього відкликані в усіх (див. 20260914_social_conversation_order_link.sql):
-- писати в базу мав тільки той, хто сидить у SQL-редакторі. Відтоді змінилося
-- головне — lib/chatbot/client-chat-lookup.ts більше не шукає діалог наосліп, а
-- читає збережений order_id. Якщо привʼязку не освіжати, Софія перестає бачити
-- кожну нову розмову, і вчорашній знімок тихо стає її картиною світу.
--
-- Оновлює /api/cron/social-unanswered, кожні пів години у робочі години, тим
-- самим сервісним ключем. Повний прохід по 66 тисячах повідомлень займає
-- близько двох із половиною секунд при maxDuration = 60, тож запас великий;
-- коли переписок стане вчетверо більше, варто перевірити це число ще раз.
--
-- anon і authenticated лишаються без права виконання: з браузера цю функцію
-- викликати нічого.

