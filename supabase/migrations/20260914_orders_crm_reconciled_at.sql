-- Коли це замовлення востаннє звіряли з KeyCRM.
--
-- НАВІЩО. Звірка вибирала замовлення за датою створення, від найновішого, і
-- брала перші двадцять пʼять. Порядок той самий на кожному запуску, позначки
-- «це вже звіряли» не було ніде, тож двадцять шосте за свіжістю замовлення і
-- всі старші не звірялися більше ніколи. Станом на 14.09.2026 зі 131
-- замовлення з сайту, що тримають знімок картки CRM, свіжий знімок мали 25,
-- старший за тиждень — 81, старший за місяць — 16. Серед них 33 усиновлені
-- картки, яких звірка не торкалася жодного разу від дня усиновлення.
--
-- Звірка — єдиний шлях, яким із CRM на сайт приходять ТТН, стадія картки,
-- отримані гроші та скасування, тож для тих 81 усе це стояло замороженим, а
-- Софія показувала знімок, ніяк не позначаючи, що це знімок.
--
-- ЩО ДАЄ КОЛОНКА. Черга: беремо не найновіші, а ті, які найдовше не звіряли.
-- Порожнє значення означає «не звіряли жодного разу» і йде першим.
--
-- Позначка ставиться на КОЖНОМУ успішному проході, навіть коли нічого не
-- змінилося: саме факт «перевірили і все збігається» ніде не записувався, і
-- саме його бракувало, щоб побудувати чергу. Не ставиться вона лише тоді,
-- коли запит до CRM провалився — інакше збійне замовлення поїхало б у кінець
-- черги, і збій став би невидимим. Відповідь «такої картки в CRM більше
-- немає» позначкою СУПРОВОДЖУЄТЬСЯ: це теж відповідь, і без неї мертва картка
-- вічно займала б місце в голові черги.
--
-- Чому окрема колонка, а не поле в custom_attributes: блок keycrm
-- переписується тільки тоді, коли щось змінилося, а нам потрібно записувати
-- саме «не змінилося»; до того ж сортування за полем усередині jsonb не лягає
-- на звичайний індекс.
--
-- updated_at ця колонка не чіпає: тригерів на orders немає, і позначка
-- ставиться або разом із рештою патча, або окремим точковим запитом.

alter table public.orders
    add column if not exists crm_reconciled_at timestamptz;

-- Індекс під саму чергу: спершу ті, кого не звіряли ніколи, далі найдавніші.
-- Часткова умова відкидає замовлення без картки в CRM — їх більшість, і в
-- черзі їм робити нічого.
create index if not exists orders_crm_reconciled_at_idx
    on public.orders using btree (crm_reconciled_at asc nulls first)
    where custom_attributes -> 'keycrm' ->> 'order_id' is not null;

comment on column public.orders.crm_reconciled_at is
    'Час останньої успішної звірки з карткою KeyCRM. NULL — не звіряли жодного '
    'разу. Ставиться і тоді, коли звірка нічого не змінила; не ставиться, коли '
    'запит до CRM провалився.';
