-- Секція «Часті питання» на сторінці товару + текст під топові запити.
--
-- Навіщо. Аудит за вересень 2026 показав, що категорійні запити стоять
-- приблизно на десятій позиції — це низ першої сторінки, куди майже не
-- клікають. Три запити з найбільшою кількістю показів за півроку:
--
--   «фотоальбом для вклеювання фото» — 1 191 і «альбом для вклеювання фото»
--        — 861, обидва ведуть на scrapbook-white-pages;
--   «книга побажань» разом з «на весілля» і «на 1 рік» — близько 1 039,
--        це wishbook і guestbook-kids;
--   «друк фото полароїд» — 217, це polaroid-print.
--
-- Сторінки під ці запити вже існують і вже канонічні, тож нових адрес тут не
-- зʼявляється. Бракувало трьох речей: питань, які людина справді ставить перед
-- покупкою, розмітки FAQPage під них і ключа в заголовку рівно тим порядком
-- слів, яким його шукають.
--
-- Колонка faq повторює домовленість landing_pages: масив обʼєктів {q, a},
-- переклади лежать у translations.{locale}.faq. Сторінка товару читає її через
-- pickFaq() і малює і видиму секцію, і schema.org FAQPage з тих самих рядків.
--
-- Цін, варіантів, опцій і зображень міграція не торкається.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Колонка
-- ─────────────────────────────────────────────────────────────────────────────

