-- Партії щоденної розсилки беруться з рядків зі статусом 'scheduled', і цей
-- індекс — рівно під той запит: status = 'scheduled', найстаріші першими.
--
-- Досі частковий індекс був тільки під 'pending', бо заготовлених рядків
-- ніколи не було більше за кількадесят. Із планом «по 100 листів на день»
-- у черзі одночасно лежить понад пʼять тисяч заготовок, і щоденна вибірка
-- сотні найстаріших без індексу читала б усю таблицю.
create index if not exists email_campaign_queue_scheduled_idx
    on public.email_campaign_queue (created_at)
    where status = 'scheduled';
