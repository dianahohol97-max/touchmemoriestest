-- email_logs: хто з адмінки натиснув «Надіслати».
--
-- Проблема: журнал вихідних листів не знав автора. Менеджер надсилав листа, і
-- за хвилину ніхто не міг сказати ні хто його надіслав, ні чи він узагалі
-- пішов. Колонка provider_message_id у таблиці вже була, але її не писав
-- ніхто — нуль значень на 255 рядків.
--
-- Два поля, а не одне, і це навмисно. sent_by тримає звʼязок зі staff, щоб
-- журнал приєднувався до співробітника як усюди в цій базі (orders.created_by,
-- inventory_movements.added_by мають рівно такий вигляд). sent_by_name тримає
-- імʼя на момент відправки, щоб запис пережив видалення співробітника — заради
-- цього задача й робилася. ON DELETE SET NULL забирає звʼязок, але не рядок і
-- не імʼя.
--
-- NULL в обох означає «надіслала система»: вебхук Monobank, крон, лист після
-- створення рахунку з боку клієнта. Людини за такою відправкою немає, і
-- вигадувати її не треба.
--
-- Перевірено перед міграцією: активних співробітників 14, у admin_users
-- четверо, і всі четверо мають рядок у staff — тобто звʼязок покриває всіх,
-- хто сьогодні може натиснути кнопку.

alter table public.email_logs
    add column if not exists sent_by uuid references public.staff(id) on delete set null,
    add column if not exists sent_by_name text;

comment on column public.email_logs.sent_by is
    'Співробітник, який натиснув «Надіслати». NULL означає автоматичну відправку.';
comment on column public.email_logs.sent_by_name is
    'Імʼя на момент відправки. Дублює staff.name навмисно: журнал має лишитися читабельним після видалення співробітника.';

-- Історія листування читається рівно так: усі листи одного замовлення,
-- найновіші зверху.
create index if not exists email_logs_order_sent_idx
    on public.email_logs (order_id, sent_at desc);
