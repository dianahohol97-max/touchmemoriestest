-- Два замовлення, позначені оплаченими вручну, лишилися зі стадією 'created'.
--
-- Проблема. Кнопка «Позначити оплаченим» писала payment_status і paid_at, але
-- monobank_invoice_status не чіпала. Доки стадія була просто довідковою, це
-- нікому не заважало. Після 20260914_monobank_stage_order вона стала
-- ЗАХИСНОЮ: apply_monobank_payment порівнює ранг події зі збереженою стадією,
-- і окреме суворе правило «після success назад тільки reversed» читає саме її.
--
-- Наслідок. Замовлення зі стадією 'created' (ранг 10) беззахисне: запізніла
-- подія 'failure' (ранг 35) проходить умову «не менший ранг» і переводить
-- підтверджену оплату у 'failed'. Тобто ручне підтвердження роззброювало
-- захист рівно на тих замовленнях, які воно щойно полагодило.
--
-- Маршрут виправлено в тому ж коміті, і виправлено з умовою: стадія
-- дописується лише там, де рахунок Monobank справді існує. Кнопку тиснуть і на
-- замовленнях, за які заплатили повз Monobank — готівкою, переказом,
-- накладеним, — і писати їм стадію банківського рахунку означало б вигадати
-- подію, якої не було.
--
-- Нижче та сама умова в даних: беруться лише рядки з monobank_invoice_id.
-- Обидва замовлення мають paid_at, тобто перехід в оплачено справді стався.
--
--   TM-001232, 23.08 — 315 грн із 629 (передоплата 50/50, рахунок на неї
--                      пройшов, тому payment_status = 'paid');
--   TM-001251, 30.08 — 775 грн, повна оплата.
--
-- Це НЕ реконструкція суми: paid_amount в обох уже правильний, міняється
-- виключно стадія інвойсу.

update public.orders
   set monobank_invoice_status = 'success',
       updated_at = now()
 where payment_status = 'paid'
   and paid_at is not null
   and monobank_invoice_id is not null
   and coalesce(monobank_invoice_status, '') <> 'success';

insert into public.order_history (order_id, action, notes, added_by)
select id,
       'payment_status_changed',
       'Виправлено міграцією 20260914_mark_paid_invoice_stage: оплату підтвердили '
       || 'вручну, і стадія рахунку Monobank лишилася застарілою. Сума не '
       || 'змінювалася, лише стадія.',
       null
  from public.orders
 where order_number in ('TM-001232', 'TM-001251');
