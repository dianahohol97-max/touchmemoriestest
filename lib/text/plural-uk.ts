/**
 * Українська форма множини: один знімок, два знімки, п'ять знімків.
 *
 * Жило копією в lib/orders/attention.ts для «день» і «година». Друга копія в
 * листі про прийняту заявку означала б дві однакові функції, які колись
 * розійдуться, а розходження тут виглядає як безграмотний лист клієнтові —
 * «2 найважчих файлів не пройшли» замість «два найважчі файли не пройшли».
 */
export function pluralUk(n: number, one: string, few: string, many: string): string {
    const abs = Math.abs(Math.trunc(Number(n) || 0));
    const mod10 = abs % 10;
    const mod100 = abs % 100;
    if (mod10 === 1 && mod100 !== 11) return one;
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
    return many;
}

/**
 * Числівник словом до двадцяти, далі цифрою.
 *
 * Правило Діани: у текстах для клієнтів малі числа пишуться словами. «Два
 * файли» читається як речення, «2 файли» — як рядок таблиці.
 */
const WORDS: Record<number, string> = {
    1: 'один', 2: 'два', 3: 'три', 4: 'чотири', 5: 'пʼять', 6: 'шість',
    7: 'сім', 8: 'вісім', 9: 'девʼять', 10: 'десять', 11: 'одинадцять',
    12: 'дванадцять', 13: 'тринадцять', 14: 'чотирнадцять', 15: 'пʼятнадцять',
    16: 'шістнадцять', 17: 'сімнадцять', 18: 'вісімнадцять', 19: 'девʼятнадцять',
    20: 'двадцять',
};

/** Жіночий рід для одного і двох: одна сторінка, дві сторінки. */
const WORDS_FEM: Record<number, string> = { 1: 'одна', 2: 'дві' };

export function numberWordUk(n: number, gender: 'm' | 'f' = 'm'): string {
    const v = Math.trunc(Number(n) || 0);
    if (v < 1 || v > 20) return String(v);
    if (gender === 'f' && WORDS_FEM[v]) return WORDS_FEM[v];
    return WORDS[v];
}
