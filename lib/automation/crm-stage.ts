/**
 * Етап KeyCRM у людському вигляді — ТІЛЬКИ для показу.
 *
 * ЗВІДКИ ПРОБЛЕМА. KeyCRM у переліку статусів віддає власні вбудовані статуси
 * під їхніми внутрішніми ключами, а стадії, які завела команда, — під тими
 * назвами, які їм дали. Мапа одна, а мови в ній дві, тож `status_label` у
 * картці буває або «Передано на друк», або `waiting_for_prepayment`. Станом на
 * 14.09.2026 сирим ключем показувалися 597 карток із 1011, тобто 59 відсотків,
 * і саме це щодня читав менеджер у календарі виробництва, на сторінці
 * «Важливо» і у відповідях Софії.
 *
 * ПЕРЕКЛАД ЖИВЕ НА ПОКАЗІ, А НЕ В ДЗЕРКАЛІ (Diana, 14.09.2026). У
 * custom_attributes.keycrm лягає рівно те, що прийшло з CRM: інакше через
 * півроку неможливо буде відповісти, що саме вона віддавала. Тому жоден
 * писач цього поля не змінено, а перекладається рядок у момент, коли його
 * показують людині.
 *
 * ЧОТИРИ ПІДБІРКИ ПІДРЯДКІВ ЦЕЙ МОДУЛЬ НЕ ЗАМІНЮЄ і не має замінювати:
 * statusFromCrm у keycrm-mirror, isClosedCrmStage у production-visibility,
 * fulfilmentFromLabel у keycrm-twoway і регулярка в risk-radar навмисно
 * розуміють ОБИДВІ мови одразу. Вони відповідають на питання «що це означає
 * для роботи», а не «як це назвати людині», і працюють правильно.
 */

/**
 * Статуси САЙТУ українською — те, чим підписують замовлення, коли етапу з CRM
 * немає або коли ключ невідомий.
 *
 * Жив двома однаковими копіями в work-questions.ts і work-commands.ts, і це
 * рівно та схема, з якої починається розходження. Тепер копія одна, а
 * маленька літера збережена як була, щоб видимий текст у чаті не змінився.
 *
 * Сторінка календаря виробництва має власний словник із великої літери
 * («Підтверджено»), і його навмисно не чіпаємо: там інше оформлення, і
 * зведення їх в один змінило б написи в адмінці без жодної на те причини.
 */
export const SITE_STATUS_UA: Record<string, string> = {
    new: 'нове',
    confirmed: 'підтверджене',
    shipped: 'відправлене',
    delivered: 'доставлене',
    completed: 'виконане',
    cancelled: 'скасоване',
};

/**
 * Вбудовані статуси KeyCRM, які зустрілися в наших картках. Список свідомо
 * НЕ доповнений здогадами: чого ми не бачили, того не перекладаємо, а показуємо
 * за правилом для невідомого ключа нижче. Так помилковий переклад неможливий
 * за побудовою, а новий ключ одразу видно і в картці, і в логах.
 */
export const CRM_STAGE_UA: Record<string, string> = {
    completed: 'Виконано',
    in_transit: 'В дорозі',
    canceled: 'Скасовано',
    delivered_to_delivery: 'Передано в доставку',
    waiting_for_prepayment: 'Очікує передоплати',
};

/**
 * Ключ чи назва. Поділ у даних абсолютно чистий: кожне значення або цілком із
 * маленьких латинських літер, цифр і підкреслень, або містить кирилицю —
 * змішаних немає жодного. Тож правило одне й без списку винятків.
 */
function isRawKey(label: string): boolean {
    return /^[a-z0-9_]+$/.test(label);
}

/** Щоб той самий невідомий ключ не засмічував лог на кожній картці. */
const reportedUnknown = new Set<string>();

function reportUnknown(key: string): void {
    if (reportedUnknown.has(key)) return;
    reportedUnknown.add(key);
    console.warn(`[crm-stage] невідомий етап KeyCRM «${key}» — додай його у CRM_STAGE_UA (lib/automation/crm-stage.ts)`);
}

/**
 * Що показати людині замість етапу з CRM.
 *
 * @param stageLabel  `custom_attributes.keycrm.status_label` як є.
 * @param siteLabel   Статус сайту, вже українською, від того, хто викликає.
 *                    Кожен споживач має власний словник із власним написанням
 *                    («Підтверджено» в адмінці, «підтверджене» в чаті), і
 *                    зводити їх в один цей модуль не береться — видимий текст
 *                    від перекладу етапу мінятися не повинен.
 *
 * Порядок такий:
 *   1. етапу немає — NULL, і це не те саме, що статус сайту. Той, хто
 *      викликає, сам вирішує, чи писати «Етап у KeyCRM», чи промовчати:
 *      у 96 замовленнях із 1107 етапу немає взагалі, бо вони до CRM не
 *      доїхали, і рядок «Етап у KeyCRM: Підтверджено» там був би вигадкою;
 *   2. етап кирилицею — це вже людська назва, віддаємо як є;
 *   3. відомий ключ — віддаємо переклад;
 *   4. невідомий ключ — статус сайту, а ключ у дужках поруч, щоб нічого не
 *      загубилося: «Підтверджено (CRM: returned)».
 */
export function crmStageLabel(
    stageLabel: string | null | undefined,
    siteLabel?: string | null,
): string | null {
    const stage = String(stageLabel || '').trim();
    const site = String(siteLabel || '').trim();

    if (!stage) return null;
    if (!isRawKey(stage)) return stage;

    const known = CRM_STAGE_UA[stage];
    if (known) return known;

    reportUnknown(stage);
    return site ? `${site} (CRM: ${stage})` : stage;
}

/**
 * Те саме, але для списків, де показати треба ЩОСЬ: етап, а як його немає —
 * статус сайту. Рівно та умова, що стояла в кожному такому рядку до цього.
 */
export function stageOrStatus(
    stageLabel: string | null | undefined,
    siteLabel: string,
): string {
    return crmStageLabel(stageLabel, siteLabel) || siteLabel;
}
