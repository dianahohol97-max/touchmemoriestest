/**
 * Скільки важить те, що ми беремо в лист клієнту, і де починається відмова.
 *
 * ТРИ РІЗНІ МЕЖІ стоять одна за одною, і плутати їх дорого — саме плутанина
 * привела до того, що Діана 17.09.2026 дочекалася кінця завантаження PDF на
 * 128,9 МБ, щоб побачити англійське «The object exceeded the maximum allowed
 * size» (TM-001309).
 *
 *   MAX_ATTACHMENT_BYTES   25 МБ — наше правило на ОДИН файл у листі.
 *   INLINE_BUDGET_BYTES     6 МБ — скільки сирих байтів влазить у сам лист.
 *                                  Усе понад це клієнт отримує посиланням, яке
 *                                  живе місяць; лист від цього не падає.
 *   STORAGE_CEILING_BYTES  ~50 МБ — стеля самого сховища, НЕ наша.
 *
 * ПРО СТЕЛЮ СХОВИЩА. Бакет `order-files` налаштований на 150 МБ, і це число
 * бреше: над ним стоїть межа рівня проєкту, і Supabase бере меншу з двох.
 * Прямих доказів два і вони збігаються. Перший: за всю історію проєкту в
 * жодному бакеті немає ЖОДНОГО обʼєкта, важчого за 50 МБ, — найбільший із
 * 45 018 файлів `photobook-uploads` важить 44,5 МБ, попри налаштовані 150 МБ, а
 * `photographer-galleries` із дозволеними двома гігабайтами тримає максимум
 * 3,7 МБ. Другий: макет 14244 на 65 МБ відмовили тим самим повідомленням, а
 * тепер і 128,9 МБ. Тобто справжня межа лежить між 44,5 і 65 МБ, і 50 МБ — це
 * саме те, що Supabase ставить типово.
 *
 * Підняти її можна лише в налаштуваннях проєкту (Storage → Upload file size
 * limit), кодом — ніяк. Але для листа це нічого не змінює: 25 МБ наше правило,
 * і воно нижче за стелю в будь-якому разі. Тому перевірка в браузері йде саме
 * проти 25 МБ, і йде ДО завантаження: гнати сто двадцять вісім мегабайтів,
 * щоб отримати відмову, — це просто змарнований час людини.
 */

/** Наше правило на один файл у листі. */
export const MAX_ATTACHMENT_BYTES = 25 * 1024 * 1024;

/** Скільки сирих байтів іде вкладенням; решта — посиланням на місяць. */
export const INLINE_BUDGET_BYTES = 6 * 1024 * 1024;

/**
 * Стеля сховища, виміряна по живих даних (див. коментар вище). Тут вона лише
 * для того, щоб число не доводилося щоразу відкопувати заново.
 */
export const STORAGE_CEILING_BYTES = 50 * 1024 * 1024;

export function formatBytes(bytes: number): string {
    const mb = Number(bytes) / 1048576;
    if (mb >= 1) return `${mb.toFixed(1).replace('.', ',')} МБ`;
    return `${Math.max(1, Math.round(Number(bytes) / 1024))} КБ`;
}

/**
 * Чому цей файл не можна взяти в лист. Порожньо — можна.
 *
 * Повідомлення каже і скільки важить файл, і що з ним робити. «Файл більший за
 * 25 МБ» без другої половини лишає людину рівно там, де вона стояла.
 */
export function rejectAttachment(file: { name: string; size: number }): string | null {
    if (!(Number(file.size) > MAX_ATTACHMENT_BYTES)) return null;
    return `${file.name} важить ${formatBytes(file.size)}, а в лист можна взяти файл до ${formatBytes(MAX_ATTACHMENT_BYTES)}. `
        + 'Збережіть макет легшим — у PDF зазвичай досить стиснути зображення до 150 dpi — '
        + 'або прикріпіть готовий файл кнопкою «З файлів замовлення», він піде посиланням.';
}
