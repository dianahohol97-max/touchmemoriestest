/**
 * Правило «той самий лист про те саме замовлення двічі не йде».
 *
 * Винесено з /api/email/transactional окремо, щоб правило можна було
 * перевірити тестом. Ціна помилки тут несиметрична: зайвий лист клієнт
 * помітить і пробачить, а загублений лист про оплату не помітить ніхто, доки
 * людина не напише сама.
 *
 * Передісторія. Лист про отриману оплату йшов двічі на 70 замовленнях із 71:
 * у вебхуку монобанку стояли два незалежні блоки відправки, обидва під
 * умовою, яка дивилася на той самий знімок замовлення, прочитаний ще до
 * UPDATE. Другий блок прибрано, але відправників дії 'paid' лишається троє —
 * вебхук, «Позначити оплаченим» і «Перевірити оплату», — тож правило має
 * стояти в одному спільному місці, а не трьома заплатками.
 */

/**
 * Скільки часу той самий лист вважається щойно надісланим.
 *
 * Вікно, а не «будь-коли», бо замовлення живе довго: лист про відправлення
 * після повторного створення ТТН через тиждень — це подія, а не дубль.
 * Година покриває і два виклики в межах одного запиту (там розрив у
 * секунди), і менеджера, який натиснув «Перевірити оплату» невдовзі після
 * вебхука.
 */
export const RESEND_GUARD_WINDOW_MINUTES = 60;

/**
 * Дії, для яких повторне надсилання законне і глушити його не можна.
 *
 * 'placed' — це лист із посиланням на оплату, і кнопка «Надіслати посилання
 * клієнту» в картці замовлення існує рівно для того, щоб надіслати його ще
 * раз. У журналі такі пари стоять із розривом у години, а не в секунди:
 * п'ять випадків із дев'яноста шести, усі до неоплачених замовлень.
 *
 * 'custom' до маршруту з номером замовлення не доходить взагалі, тож у
 * списку йому місця немає.
 */
const RESEND_ALLOWED_ACTIONS = new Set(['placed']);

/**
 * Чи підпадає дія під захист від повторів.
 *
 * Дія приходить із тіла запиту, тобто ззовні, тому нерядок — це «так,
 * захищаємо»: невідоме краще придушити, ніж надіслати двічі.
 */
export function isResendGuarded(action: unknown): boolean {
    if (typeof action !== 'string') return true;
    return !RESEND_ALLOWED_ACTIONS.has(action.trim());
}

/**
 * Початок вікна, з якого шукаємо вже надісланий лист.
 *
 * Момент передається аргументом, щоб тест не залежав від годинника.
 */
export function resendGuardSince(now: Date = new Date()): string {
    return new Date(now.getTime() - RESEND_GUARD_WINDOW_MINUTES * 60_000).toISOString();
}
