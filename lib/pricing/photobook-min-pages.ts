/**
 * Мінімальна кількість розворотів для кожного розміру фотокниги.
 *
 * НАВІЩО ОКРЕМИЙ ФАЙЛ. Ця таблиця жила в картці товару ДВІЧІ — раз у
 * обробнику зміни розміру (щоб підняти вже обраний розворот до нового
 * мінімуму) і раз у фільтрі списку (щоб зайве не показувалось). Дві копії
 * однакових чисел в одному файлі — це та сама пастка, що колись була з
 * панеллю слота: вони збігаються рівно доти, доки хтось не поправить одну.
 *
 * ЩО ЦЕ ЗА ЧИСЛА. Не технічне обмеження, а виробниче: 30×30 на шість
 * розворотів просто не роблять (Діана, 15.09.2026). Таблиця цін
 * photobook_prices мусить мати рядок для кожної пари «розмір + розворот», яку
 * ці мінімуми дозволяють обрати, і не мати жодного зайвого — інакше з'являються
 * ціни на те, чого не існує. Станом на 15.09.2026 три преміальні обкладинки
 * (тканина, шкірзам, велюр) сходяться з цією таблицею точно, а в друкованої
 * лежало десять зайвих рядків, кожен із ціною, просто скопійованою з першого
 * справжнього тарифу свого розміру.
 *
 * ЯКЩО МІНІМУМ МІНЯЄТЬСЯ: поправити тут, а тоді звірити photobook_prices —
 * новий дозволений розворот без рядка в таблиці цін означає товар, який можна
 * обрати й не можна порахувати.
 */
export const PHOTOBOOK_MIN_PAGES: Record<string, number> = {
    '20x20': 6,
    '25x25': 8,
    '20x30': 10,
    '30x20': 10,
    '30x30': 16,
};

/**
 * Розмір приходить у картку трьома написаннями — «20х20» з кириличною х,
 * «20x20» з латинською і «20×20» зі знаком множення, іноді з «см» на хвості.
 * Ключ один, тож нормалізація теж одна.
 */
export function photobookSizeKey(size: string | number): string {
    return String(size ?? '')
        .toLowerCase()
        .replace(/[х×]/g, 'x')
        .replace(/\s*см\s*$/, '')
        .trim();
}

/** Скільки розворотів щонайменше для цього розміру. Нуль — розмір невідомий. */
export function minPagesForSize(size: string | number): number {
    return PHOTOBOOK_MIN_PAGES[photobookSizeKey(size)] ?? 0;
}
