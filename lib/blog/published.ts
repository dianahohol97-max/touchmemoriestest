/**
 * Гейт видимості посту блогу за датою публікації.
 *
 * НАВІЩО. Черга статей пишеться наперед і має відкриватися за графіком, а
 * `blog_posts` до 21.09.2026 знала тільки прапорець `is_published`. Виходило
 * дві однаково погані дороги: лишити `is_published = false` і відкривати
 * кожну статтю руками в потрібний день, або поставити `true` заздалегідь — і
 * тоді пост стає видимим одразу, ще й першим у списку, бо всі вісім місць
 * сортують за `published_at desc`. Дата в майбутньому піднімала б чернетку
 * над усіма живими статтями, і те саме поїхало б у RSS і в `sitemap.xml`.
 *
 * РІШЕННЯ. Дата публікації тепер справді керує показом: пост видно тоді, коли
 * `is_published = true` І `published_at` уже настала. Окремого крона під це не
 * заводили — сторінки блогу стоять на ISR (`revalidate` 3600 у списку і 7200 у
 * пості), тож наступна регенерація після настання дати сама підхоплює статтю.
 * Крон довелося б тримати вічно заради того, що ISR робить сам.
 *
 * ЧОМУ NULL ЛИШАЄТЬСЯ ВИДИМИМ. Простий `.lte('published_at', now)` відсіює
 * рядки з `NULL`, бо в SQL порівняння з NULL не істинне. Серед шістнадцяти
 * наявних постів ключів до бази звідси немає, тож перевірити, чи є серед них
 * порожня дата, нема чим — а ціна помилки несиметрична: зникла стаття не
 * падає, не світиться червоним і виявляється тільки тоді, коли хтось її
 * шукатиме. Тому NULL читається як «опубліковано давно» і поведінку наявних
 * постів ця зміна не міняє взагалі: гейт відрізає рівно те, що має дату в
 * майбутньому.
 *
 * ТРЕТЯ УМОВА, З 22.09.2026. Разом із чергою зʼявився стовпець `status`, і
 * гейт тепер питає ще й його. Умова СТРОГІША за попередні дві, а не ширша:
 * стаття без `status = 'published'` ховається, навіть якщо прапорець і дата
 * кажуть протилежне. Через це нічого зайвого відкритися не може, а от забутий
 * `status` зробив би статтю невидимою — саме тому публікація і зняття з
 * публікації живуть одними функціями в `lib/blog/queue.ts`, які пишуть усі
 * три поля разом.
 *
 * Додаючи дев'яте місце, яке читає `blog_posts` для відвідувача, клади фільтр
 * сюди, а не поруч: на це стоїть tests/blog-schedule.test.ts, який перелічує
 * всі читання по репозиторію і падає на тому, що обійшло цей файл.
 */

/** Межа відсікання у форматі, який розуміє PostgREST. */
export function publishedCutoff(now: Date = new Date()): string {
    return now.toISOString();
}

/** Умова `or(...)` одним рядком — щоб і код, і тест називали її однаково. */
export function publishedAtFilter(now: Date = new Date()): string {
    return `published_at.is.null,published_at.lte.${publishedCutoff(now)}`;
}

/**
 * Лишає в запиті тільки ті пости, які відвідувач має право бачити просто зараз.
 *
 * Обгортка навмисно приймає і повертає той самий будівник запиту, щоб її можна
 * було вставити в наявний ланцюжок `.select().order().range()` без перестановок.
 */
export function onlyVisiblePosts<T>(query: T, now: Date = new Date()): T {
    return (query as any)
        .eq('status', 'published')
        .eq('is_published', true)
        .or(publishedAtFilter(now)) as T;
}
