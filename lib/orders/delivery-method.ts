/**
 * Спосіб доставки людською мовою.
 *
 * У базі це слаг — `nova_poshta`, `pickup`, `other`. Показувати слаг людині
 * немає сенсу ніде: ні менеджерові в CRM, ні виробництву в аркуші на друк.
 * Словник жив у вивантаженні в KeyCRM і був там єдиною копією; коли та сама
 * назва знадобилася виробництву, правильним було винести його, а не написати
 * другий поруч.
 */
export const DELIVERY_LABELS: Record<string, string> = {
    nova_poshta: 'Нова Пошта',
    ukrposhta: 'Укрпошта',
    pickup: 'Самовивіз',
    courier: "Кур'єр",
    digital: 'Електронна доставка',
    international: 'Міжнародна відправка',
    // Не «інше», а прямим текстом: спосіб доставки ще не узгоджений із
    // клієнтом. Раніше такі замовлення приходили в CRM як «Самовивіз», і
    // менеджер не мав підстав переспитати.
    other: 'Не обрано — узгодити з клієнтом',
};

/** Назва способу доставки; невідомий слаг повертається як є, а не ховається. */
export function deliveryMethodLabel(method: any): string {
    const key = String(method ?? '').trim();
    return DELIVERY_LABELS[key] || key;
}
