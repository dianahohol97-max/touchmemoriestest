/**
 * Чий це макет.
 *
 * ЧОМУ ЦЕ ІСНУЄ. Макет, зібраний у конструкторі, їде до замовлення під ключем
 * рядка кошика: `design_{cartItemId}` у сховищі вкладки і
 * `projects.cart_payload->>id` у базі. Ключ є, а от перевірки, що під ключем
 * лежить саме той макет, не було ніде.
 *
 * На TM-001342 це коштувало цілої книги. Клієнтка зібрала дві РІЗНІ тревелбуки
 * в одному конструкторі, жодного спільного фото між ними, і оплатила обидві
 * одним замовленням. До першого рядка кошика, оціненого за 65 фото і 16
 * сторінок, у підсумку лягли 68 фото і 22 сторінки другої книги, а перша
 * книга лишилася непривʼязаною чернеткою. У друк поїхали б дві копії однієї
 * книги, і помітила це менеджерка очима, звіряючи картку з CRM.
 *
 * Тому макет тепер несе в собі той ключ, під яким його зберегли, і обидві
 * сторони — оформлення в браузері й маршрут save-design на сервері —
 * відмовляються класти його під чужий ключ. Відмова тут краща за запис:
 * позиція без макета видна і сторожу тихих втрат, і перевірці файлів перед
 * друком, а позиція з ЧУЖИМ макетом виглядає справною рівно до друку.
 */

/** Кому належить макет за його власною позначкою. Порожньо — позначки немає. */
export function designOwnerId(design: unknown): string | null {
    if (!design || typeof design !== 'object') return null;
    const raw = (design as Record<string, unknown>).cartItemId;
    const id = typeof raw === 'string' ? raw.trim() : '';
    return id || null;
}

export type OwnershipVerdict = 'ok' | 'unstamped' | 'foreign';

/**
 * Чи можна зберегти цей макет під цим ключем.
 *
 * `unstamped` — це макети, зібрані до появи позначки. Вони зберігаються як
 * раніше: відмовити їм означало б викинути справні замовлення заради захисту
 * від того, що вже сталося.
 */
export function checkDesignOwnership(design: unknown, cartItemId: string | null | undefined): OwnershipVerdict {
    const owner = designOwnerId(design);
    if (!owner) return 'unstamped';
    const target = String(cartItemId || '').trim();
    if (!target) return 'unstamped';
    return owner === target ? 'ok' : 'foreign';
}
