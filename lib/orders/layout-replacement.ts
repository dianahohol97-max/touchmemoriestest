/**
 * Який макет замовлення заміщає виправлена чернетка дизайнера.
 *
 * ЧОМУ ЦЕ ОКРЕМО І ПІД ТЕСТАМИ. Кнопка «Поставити на замовлення» обіцяє
 * ЗАМІНУ, і поки вона відбирала замінюване за `product_type`, вона мовчки
 * робила інше — ДОДАВАЛА. Той самий фізичний товар зберігається під різними
 * значеннями `product_type` залежно від того, який шлях його зберіг:
 * `personalized-glossy-magazine` конструктор кладе як `journal`, а оформлення
 * як `magazine`. На TM-001352 через це збіглося рівно нічого: на замовленні
 * стояв `journal`, у чернетці лежав `magazine`, збігу не було, нічого не
 * відчепилося, і замовлення отримало ДРУГИЙ виріб — той самий червоний блок
 * «0 файлів», який щойно прибирали руками.
 *
 * Правильна тотожність тут — КЛЮЧ ПОЗИЦІЇ КОШИКА. Саме ним увесь інший код
 * відповідає на питання «до якого рядка замовлення належить цей макет»
 * (`design_{cartItemId}` у сховищі, `projects.cart_payload->>id` у базі, гоча
 * 18). Він не залежить від того, хто саме зберіг макет, і не міняється від
 * перезбереження.
 *
 * `product_type` лишається ЗАПАСНИМ варіантом: чернетки, зроблені до появи
 * ключа, його не мають, і викидати їх із заміни не можна — для них поведінка
 * лишається рівно такою, як була.
 *
 * Вартість помилки тут несиметрична в обидва боки, і саме тому правило чисте.
 * Заміщати ЗАЙВЕ — це відчепити чужу книгу того самого замовлення (так
 * TM-001234 двічі втрачало готовий макет). Заміщати НЕДОСТАТНЬО — це те, що
 * сталося з TM-001352: два вироби замість одного і макет-привид у картці.
 */

export interface LayoutRow {
    id: string;
    product_type?: string | null;
    cart_payload?: unknown;
    created_at?: string | null;
}

/** Ключ позиції кошика, під який збережено цей макет, або null. */
export function cartKeyOf(row: Pick<LayoutRow, 'cart_payload'> | null | undefined): string | null {
    const payload = row?.cart_payload;
    if (!payload || typeof payload !== 'object') return null;
    const id = (payload as Record<string, unknown>).id;
    const key = String(id ?? '').trim();
    return key || null;
}

/**
 * Макети замовлення, які ця чернетка заміщає.
 *
 * Спершу за ключем позиції. Якщо ключа немає в чернетці або жоден із поточних
 * макетів його не поділяє — падаємо на старе порівняння за `product_type`, бо
 * інакше чернетки, зроблені до появи ключа, перестали б заміщати будь-що.
 *
 * Сама чернетка зі списку виключається завжди: заміщати себе безглуздо, а
 * відчепити себе перед тим, як причепитися, означало б втратити привʼязку.
 */
export function layoutsReplacedBy(draft: LayoutRow, current: LayoutRow[]): LayoutRow[] {
    const others = (current || []).filter(p => p && p.id !== draft.id);
    const key = cartKeyOf(draft);
    if (key) {
        const byKey = others.filter(p => cartKeyOf(p) === key);
        if (byKey.length > 0) return byKey;
    }
    const type = String(draft.product_type || '');
    if (!type) return [];
    return others.filter(p => String(p.product_type || '') === type);
}

/**
 * Ті з заміщуваних макетів, які СТВОРЕНІ ПІЗНІШЕ за чернетку.
 *
 * Це і є питання «чи не ставлю я старішу версію замість новішої». Порівняння
 * саме за створенням, а не за `updated_at`: останній рухається від речей, які
 * до дизайну стосунку не мають — відчеплення макета від замовлення, відновлення
 * втрачених шляхів до фото перед рендером, сама ця заміна. Дата створення
 * такого не робить і чесно відповідає на питання «що зроблено пізніше».
 *
 * Відповідь тут НЕ забороняє заміну, а дає підставу спитати людину: буває, що
 * пізніший макет і є той, який треба відкотити.
 */
export function newerThanDraft(draft: LayoutRow, replaced: LayoutRow[]): LayoutRow[] {
    const draftAt = Date.parse(String(draft.created_at || ''));
    if (!Number.isFinite(draftAt)) return [];
    return (replaced || []).filter(p => {
        const at = Date.parse(String(p?.created_at || ''));
        return Number.isFinite(at) && at > draftAt;
    });
}
