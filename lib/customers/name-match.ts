/**
 * Чи це та сама людина — за іменем.
 *
 * Потрібне, щоб прив'язати гостьове замовлення до акаунта з тією самою поштою.
 * Пошта сама по собі не доказ: родина ділить одну адресу, і в базі це вже є —
 * з акаунта «Svitlana Krasnova» систематично замовляє «Ірина Байдакова», а з
 * «Julia Savkiv» приходило замовлення на «Савків Наталія», де прізвище те саме,
 * а ім'я інше. Прив'язати такі означає показати людині в кабінеті чужі
 * замовлення з чужими адресами доставки.
 *
 * ПРАВИЛО ПОМИЛЯЄТЬСЯ В БІК РУЧНОЇ ПЕРЕВІРКИ, І ЦЕ НАВМИСНО (Діана, 14.09.2026).
 * Прив'язуємо лише там, де є позитивний доказ тотожності; усе інше показуємо
 * менеджерові. Зайва хвилина його часу дешевша за чуже замовлення в кабінеті.
 *
 * Чого тут свідомо НЕМАЄ: списку зменшувальних форм. «саша» і «Олександра»,
 * «Ліза» і «Єлизавета» різні за коренем, і звести їх можна тільки переліком.
 * Такий перелік доводилося б вічно доповнювати, а перша ж пропущена пара дала
 * б або хибну прив'язку, або незрозумілий виняток. Тому зменшувальні йдуть на
 * перевірку разом з усіма (Діана, 14.09.2026). Якщо побачимо, що їх десятки —
 * повернемося до переліку з даними на руках.
 */

export type NameMatchVerdict = 'match' | 'review';

export interface NameMatchResult {
    verdict: NameMatchVerdict;
    /** Чому саме так — потрапляє в адмінку, щоб менеджер не гадав. */
    reason: string;
    /** Скільки слів зійшлося. Для 'match' завжди достатньо за правилом нижче. */
    matchedTokens: number;
}

/**
 * Літери, які різняться між російським і українським написанням ОДНОГО імені.
 *
 * «Мария» і «Марія», «Литвин» і «Літвін», «Феер» і «Феєр» — це та сама людина,
 * яка в картці і в замовленні написана різними абетковими звичками. Згортаємо
 * кожну групу в одну літеру, і три такі пари з десяти підозрілих зникають
 * самі.
 */
const CYRILLIC_FOLD: Record<string, string> = {
    'і': 'и', 'ї': 'и', 'й': 'и', 'ы': 'и',
    'е': 'е', 'є': 'е', 'ё': 'е', 'э': 'е',
    'ґ': 'г',
    'ь': '', 'ъ': '',
};

/**
 * Кирилиця в латиницю.
 *
 * Порядок важливий: спершу дво- і трилітерні сполуки, інакше «щ» перетвориться
 * на «sh»+«ch» і перестане збігатися з написанням «shch».
 *
 * Ціль НЕ в тому, щоб вийшла правильна транслітерація за стандартом. Ціль —
 * щоб «Бучинська» і «Buchynska» дали однаковий рядок, а люди пишуть себе
 * латиницею як завгодно: Anastasia, Anastasya, Anasnasiia — усе це одне ім'я.
 * Тому голосні зводяться агресивно, а порівняння нижче йде за спільним
 * початком слова, а не за точною рівністю.
 */
const CYR_TO_LAT: Array<[RegExp, string]> = [
    [/щ/g, 'sh'], [/ш/g, 'sh'], [/ч/g, 'ch'], [/ж/g, 'zh'], [/х/g, 'h'],
    [/ц/g, 'c'], [/ю/g, 'u'], [/я/g, 'a'],
    [/а/g, 'a'], [/б/g, 'b'], [/в/g, 'v'], [/г/g, 'h'], [/д/g, 'd'],
    [/е/g, 'e'], [/з/g, 'z'], [/и/g, 'i'], [/к/g, 'k'], [/л/g, 'l'],
    [/м/g, 'm'], [/н/g, 'n'], [/о/g, 'o'], [/п/g, 'p'], [/р/g, 'r'],
    [/с/g, 's'], [/т/g, 't'], [/у/g, 'u'], [/ф/g, 'f'],
];

/**
 * Латиниця до того самого спрощеного вигляду, що й транслітерована кирилиця.
 *
 * Сполуки прибираються так само, як вище, а подвоєні голосні стискаються:
 * «Yuliia» і «Юлія» мають зійтися, а «ii» проти «i» їх би розвело.
 */
function foldLatin(s: string): string {
    return s
        .replace(/shch/g, 'sh')
        .replace(/kh/g, 'h')
        .replace(/ts/g, 'c')
        .replace(/ya|ia|ja/g, 'a')
        .replace(/yu|iu|ju/g, 'u')
        .replace(/ye|ie|je/g, 'e')
        .replace(/y/g, 'i')
        .replace(/g/g, 'h')
        .replace(/([aeiou])\1+/g, '$1');
}

/** Чи є в рядку кирилиця. Потрібне тільки для пояснення в adminці. */
export function hasCyrillic(s: string): boolean {
    return /[Ѐ-ӿ]/.test(s);
}

/**
 * Один рядок імені до вигляду, у якому його можна порівнювати.
 *
 * Апострофи всіх видів і дефіси прибираються: «Дар'я», «Дарʼя» і «Даря» мають
 * бути одним словом, а «Гловʼяк» не має розпадатися надвоє.
 */
export function normaliseName(raw: unknown): string[] {
    if (typeof raw !== 'string') return [];
    let s = raw.toLowerCase().trim();
    if (!s) return [];

    s = s.replace(/['’`ʼ‘´]/g, '').replace(/[-–—]/g, ' ');
    s = s.replace(/[^\p{L}\s]/gu, ' ');

    s = Array.from(s).map((ch) => (ch in CYRILLIC_FOLD ? CYRILLIC_FOLD[ch] : ch)).join('');
    for (const [re, to] of CYR_TO_LAT) s = s.replace(re, to);
    s = foldLatin(s);

    return s.split(/\s+/).filter((t) => t.length >= 3);
}

/**
 * Чи два слова — одне й те саме ім'я.
 *
 * Порівняння за спільним початком, бо закінчення гуляють: «Анастасія» проти
 * «Anastasya», «Ольга» проти «Olya». Поріг у чотири літери — компроміс: три
 * зводять разом забагато коротких прізвищ, п'ять розводять «Юля» і «Yuliia».
 */
function tokensMatch(a: string, b: string): boolean {
    if (a === b) return true;
    if (Math.min(a.length, b.length) < 4) return false;
    return a.slice(0, 4) === b.slice(0, 4);
}

/**
 * Порівняння імені в картці клієнта з іменем у замовленні.
 *
 * Рішення:
 *
 *   * обидва імені з двох і більше слів — потрібно ДВА збіги. Саме це відсіює
 *     родину на спільній пошті: у «Julia Savkiv» проти «Савків Наталія»
 *     прізвище збігається, а ім'я ні, і одного збігу було б досить, щоб
 *     прив'язати чуже замовлення;
 *   * одне з імен складається з одного слова — досить одного збігу, бо більше
 *     порівнювати нічим;
 *   * жодного збігу, або в картці сміття на кшталт «К K» чи «iqd», де після
 *     нормалізації не лишається слів — на перевірку.
 */
export function matchCustomerName(cardName: unknown, orderName: unknown): NameMatchResult {
    const card = normaliseName(cardName);
    const order = normaliseName(orderName);

    if (!card.length || !order.length) {
        return { verdict: 'review', reason: 'в одному з імен немає слів для порівняння', matchedTokens: 0 };
    }

    const matched = new Set<string>();
    for (const a of card) {
        for (const b of order) {
            if (tokensMatch(a, b)) matched.add(a);
        }
    }
    const count = matched.size;
    const need = card.length >= 2 && order.length >= 2 ? 2 : 1;

    if (count >= need) {
        return { verdict: 'match', reason: `зійшлося слів: ${count}`, matchedTokens: count };
    }
    return {
        verdict: 'review',
        reason: count === 0
            ? 'жодне слово імені не зійшлося'
            : `зійшлося лише одне слово з двох потрібних — можлива родина на спільній пошті`,
        matchedTokens: count,
    };
}

/**
 * Останні дев'ять цифр номера — те, що можна порівнювати.
 *
 * Люди пишуть +380, 0, 380 і з пробілами як завгодно. Дев'ять цифр — це номер
 * без коду країни і без ведучого нуля.
 */
export function phoneTail(raw: unknown): string | null {
    if (typeof raw !== 'string') return null;
    const digits = raw.replace(/\D/g, '');
    return digits.length >= 9 ? digits.slice(-9) : null;
}

/**
 * Повне рішення про прив'язку одного замовлення до однієї картки.
 *
 * Телефон перевіряється ДОДАТКОВО до імені і може лише посилити обережність,
 * ніколи не послабити: збіг імен при різних телефонах — це сигнал, що за
 * поштою двоє людей. На сьогодні спрацьовує майже ніколи, бо телефон
 * заповнений у 12 карток із 1280 (заміряно 14.09.2026), але коштує він нічого.
 */
export function shouldLinkOrder(args: {
    cardName: unknown;
    orderName: unknown;
    cardPhone?: unknown;
    orderPhone?: unknown;
}): NameMatchResult {
    const byName = matchCustomerName(args.cardName, args.orderName);
    if (byName.verdict === 'review') return byName;

    const a = phoneTail(args.cardPhone);
    const b = phoneTail(args.orderPhone);
    if (a && b && a !== b) {
        return {
            verdict: 'review',
            reason: 'ім’я збіглося, але телефони різні — можливо, це двоє людей',
            matchedTokens: byName.matchedTokens,
        };
    }
    return byName;
}
