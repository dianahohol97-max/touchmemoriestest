/**
 * Хто везе посилку — і чи вміє наш трекінг її відстежити.
 *
 * ЧОМУ ЦЕ ОКРЕМИЙ МОДУЛЬ. Поле `orders.tracking_carrier` заповнюють три різні
 * місця, і кожне вкладало в нього свій сенс. Адмінка на міжнародних
 * відправленнях пише мітку `nova_poshta_intl`. Синк із KeyCRM пише назву
 * служби людською мовою, тобто «Нова Пошта». А внутрішні замовлення, створені
 * на сайті, не пишуть нічого й лишають NULL.
 *
 * Крон відстеження читав це поле за правилом «порожнє означає внутрішню Нову
 * Пошту, будь-яке заповнене — міжнародну доставку». Правило працювало рівно
 * доти, доки ТТН не почали приїжджати з KeyCRM: 61 замовлення з написом
 * «Нова Пошта» крон відкинув як міжнародні й ніколи не питав про них статус.
 *
 * Тепер рішення ухвалює одна функція, і вона дивиться на НАЗВУ, а не на факт
 * заповненості поля.
 */

/**
 * Чи це внутрішня відправка Новою Поштою, статус якої віддає домашній API
 * api.novaposhta.ua.
 *
 * Порожнє поле — так, це історична позначка внутрішнього відправлення.
 * «Нова Пошта» у будь-якому написанні — теж так. Міжнародна мітка, Укрпошта,
 * Meest, DHL і будь-яка інша служба — ні: їхні номери домашній трекінг не
 * знає, і питати про них немає сенсу.
 */
export function isDomesticNovaPoshta(carrier: string | null | undefined): boolean {
    const c = String(carrier ?? '').trim().toLowerCase();
    if (!c) return true;
    // Міжнародну відправку позначають окремо, і вона може називатися так само
    // «Нова Пошта», тому перевіряємо мітку ПЕРШОЮ.
    if (c.includes('intl') || c.includes('internation') || c.includes('міжнар') || c.includes('global')) return false;
    return c.includes('нова пошта') || c.includes('новапошта') || c.includes('nova poshta')
        || c.includes('novaposhta') || c.includes('nova_poshta') || c === 'np';
}
