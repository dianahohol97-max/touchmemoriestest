export const TTN_SWITCH_KEY = 'site_ttn_enabled';

/** Текст відмови. Один на обидва маршрути, щоб вони не розійшлися. */
export const TTN_DISABLED_MESSAGE =
    'Створення накладних із сайту тимчасово вимкнено (Діана, 18.09.2026): '
    + 'відправник береться не з тієї налаштовки, тож накладна вийшла б на неправильну особу. '
    + 'Робіть накладну в KeyCRM, як і досі. Увімкнути назад — рядок site_ttn_enabled у налаштуваннях.';

type SettingsReader = { from: (table: string) => any };

export type TtnSwitch = { enabled: boolean; reason: 'on' | 'off' | 'no-row' | 'unreadable' };

/**
 * Читання вимикача. Будь-яка невизначеність означає «заборонено» — див. шапку.
 */
export async function readTtnSwitch(supabase: SettingsReader): Promise<TtnSwitch> {
    try {
        const { data, error } = await supabase
            .from('settings').select('value').eq('key', TTN_SWITCH_KEY).maybeSingle();
        if (error) return { enabled: false, reason: 'unreadable' };
        if (!data) return { enabled: false, reason: 'no-row' };
        return isFlagOn((data as any).value)
            ? { enabled: true, reason: 'on' }
            : { enabled: false, reason: 'off' };
    } catch {
        return { enabled: false, reason: 'unreadable' };
    }
}
