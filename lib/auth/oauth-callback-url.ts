/**
 * Адреса, на яку Supabase повертає людину після входу.
 *
 * Чому це окремий модуль. Адресу повернення задають ЧОТИРИ місця: кнопка
 * Google на сторінці входу, така сама кнопка на сторінці реєстрації, кнопка в
 * модалці входу і лист підтвердження пошти. Поки кожне з них будувало рядок
 * саме собі, всі чотири вели повз серверний маршрут
 * app/[locale]/auth/callback/route.ts — і прив'язка гостьових замовлень разом
 * із заповненням імені з метаданих, які там живуть, не виконувалися жодного
 * разу. Одне правило в одному місці, щоб четвертий виклик не розійшовся з
 * трьома іншими.
 *
 * Тут немає звернень до window: усе приходить аргументами, тому функції
 * перевіряються тестами без браузера.
 */

/** Ті самі п'ять локалей, що в middleware і в самому маршруті. */
const LOCALES = ['uk', 'en', 'ro', 'pl', 'de'];

/** Локаль за першим сегментом шляху. Невідоме означає українську. */
export function localeFromPath(pathname: string | null | undefined): string {
    const seg = (pathname || '').split('/')[1] || '';
    return LOCALES.includes(seg) ? seg : 'uk';
}

/**
 * Шлях, на який можна повернути людину після входу.
 *
 * Приймається лише відносний шлях свого сайту. Рядок на кшталт `//evil.com`
 * браузер читає як зовнішню адресу, тож він відкидається разом із будь-яким
 * `https://…`: інакше посилання виду `/login?next=//evil.com` відправляло б
 * людину на чужий сайт одразу після входу, і зробило б це з довіреного
 * домену. Те саме правило вже стоїть на сторінці входу, звідки воно й узяте.
 */
export function safeNextPath(raw: string | null | undefined): string | null {
    if (typeof raw !== 'string') return null;
    const value = raw.trim();
    if (!value) return null;
    return /^\/(?!\/)/.test(value) ? value : null;
}

/**
 * Повна адреса серверного маршруту зворотного виклику.
 *
 * `origin` має бути канонічним доменом, а не `window.location.origin`:
 * прев'ю-збірки Vercel живуть на тимчасових адресах, які зникають після
 * наступного деплою, і повернення на таку адресу дає 404.
 *
 * `next` — сторінка, з якої людина починала. Вона потрібна для модалки входу:
 * модалку відкривають поверх конструктора або картки товару, щоб продовжити
 * почате, і повернення в кабінет замість тієї сторінки виглядало б як
 * загублена дія. Коли `next` немає або він не пройшов перевірку, маршрут веде
 * в кабінет.
 */
/**
 * Адреса, на яку веде лист про скидання пароля.
 *
 * Живе поруч із адресою зворотного виклику навмисно: це два боки одного
 * питання «куди Supabase повертає людину», і саме розбіжність між ними
 * коштувала нам робочого відновлення пароля. Модалка входу слала на
 * `/auth/reset` — адресу, за якою немає жодного маршруту, тобто людина з
 * листа впиралася в 404 і пароль не змінювала. Сторінка /forgot-password весь
 * цей час вела правильно, тож дефект бачили тільки ті, хто починав із
 * модалки.
 *
 * Сторінка має ЛИШИТИ код собі: вона обмінює його і не йде нікуди, бо саме на
 * ній вводять новий пароль. Тому вона окремим рядком виключена з перехоплення
 * в lib/auth/oauth-code-interception.ts.
 */
export function resetPasswordUrl(origin: string, pathname: string): string {
    const locale = localeFromPath(pathname);
    return `${origin.replace(/\/+$/, '')}/${locale}/reset-password`;
}

export function oauthCallbackUrl(
    origin: string,
    pathname: string,
    next?: string | null,
): string {
    const locale = localeFromPath(pathname);
    const base = `${origin.replace(/\/+$/, '')}/${locale}/auth/callback`;
    const safe = safeNextPath(next);
    return safe ? `${base}?next=${encodeURIComponent(safe)}` : base;
}
