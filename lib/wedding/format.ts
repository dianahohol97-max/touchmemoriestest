// Дата весілля словами: «10 жовтня 2026».
//
// Через Intl цього не отримати в потрібному вигляді — uk-UA додає «р.» у кінці,
// а прибирати його рядковими операціями означає залежати від того, що поверне
// бібліотека в конкретній версії Node. Місяців дванадцять, вони не змінюються,
// і явний список коротший за будь-яке обхідне рішення.
const MONTHS_GENITIVE = [
  'січня', 'лютого', 'березня', 'квітня', 'травня', 'червня',
  'липня', 'серпня', 'вересня', 'жовтня', 'листопада', 'грудня',
];

/**
 * Приймає дату у вигляді, у якому її віддає Postgres для типу date — «2026-10-10».
 *
 * Розбираємо рядок самі, а не через new Date(): конструктор тлумачить такий
 * рядок як північ за UTC, і в браузері гостя на захід від Гринвіча дата
 * зсунулася б на день назад. Весілля 10 жовтня показувалося б як 9 жовтня.
 */
export function formatWeddingDate(isoDate: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(isoDate.trim());
  if (!match) return isoDate;

  const [, year, month, day] = match;
  const monthName = MONTHS_GENITIVE[Number(month) - 1];
  if (!monthName) return isoDate;

  return `${Number(day)} ${monthName} ${year}`;
}
