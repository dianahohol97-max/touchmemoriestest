// Пайлот весільної сторінки — спільні межі та типи (Діана, 16.09.2026).
//
// Тут лежать числа, які мусять збігатися на клієнті й на сервері. Якщо ліміт
// живе у двох місцях окремо, вони розходяться: клієнт пропускає файл, сервер
// його відхиляє, і гість бачить помилку вже після очікування на завантаження.

/** Бакет саме для весільних фото. */
//
// Навмисно НЕ order-files: там файли самознищуються через 90 днів, бо це
// матеріали до замовлення, які після друку не потрібні. Весільні фото живуть
// стільки, скільки схоче пара, тож автовидалення над ними стояти не може.
// Бакет приватний, і жодної політики на storage.objects для нього немає:
// покласти й прочитати може лише службова роль, тобто наші роути.
export const WEDDING_BUCKET = 'wedding-photos';

/** Скільки файлів гість надсилає за один раз. */
export const MAX_FILES_PER_BATCH = 20;

/**
 * Межа на один файл ДО стиснення.
 *
 * Гість вибирає з галереї те, що зняв телефон, і 15 МБ покривають і HEIC з
 * iPhone, і HDR з Android. Стиснення відбувається до відправки, тож на сервер
 * приходить уже щось близько мегабайта.
 */
export const MAX_FILE_BYTES = 15 * 1024 * 1024;

/**
 * Межа на те, що реально долітає до сервера.
 *
 * Стиснення може не спрацювати — браузеру бракує памʼяті, картинка з дивним
 * профілем, старий телефон. Тоді летить оригінал, і цей запас мусить його
 * пропустити, інакше гість втратить фото через нашу оптимізацію. Збігається з
 * file_size_limit бакета.
 */
export const MAX_UPLOAD_BYTES = 20 * 1024 * 1024;

/** Довша сторона після стиснення. */
//
// 2560 достатньо, щоб з фото потім надрукувати розворот фотокниги, і вдвічі
// менше за оригінал з телефона за обсягом. Весільний Wi-Fi цього не помітить,
// а от оригінали на 8 МБ помітить одразу.
export const MAX_LONG_EDGE = 2560;

/** Якість JPEG після стиснення. */
export const JPEG_QUALITY = 0.85;

/** Типи, які приймає і бакет, і роут завантаження. */
export const ALLOWED_MIME = ['image/jpeg', 'image/png', 'image/webp'] as const;

/** Як часто сторінка питає про нові фото. */
//
// Опитування, а не realtime: підписка тримає сокет відкритим у кожного гостя,
// а весілля — це десятки телефонів у поганій мережі. П'ятнадцять секунд на
// весіллі непомітні, зате сторінка переживає втрату зв'язку без перепідключень.
export const GALLERY_POLL_MS = 15_000;

/** Скільки фото віддається за одну сторінку галереї. */
export const GALLERY_PAGE_SIZE = 48;

export interface WeddingEvent {
  id: string;
  slug: string;
  couple_names: string;
  event_date: string;
  hero_photo_path: string | null;
}

export interface WeddingPhoto {
  id: string;
  guest_name: string | null;
  width: number | null;
  height: number | null;
  created_at: string;
}

/** Адреса, якою сторінка показує одне фото. Її ж оптимізує next/image. */
export const photoUrl = (id: string) => `/api/wedding/photo/${id}`;

/** Адреса фото пари для шапки. */
export const heroUrl = (slug: string) => `/api/wedding/${slug}/hero`;

/** Запасне фото пари, поки hero_photo_path порожній. */
//
// Лежить у репозиторії тільки як тимчасова заглушка. Щойно в бакет покладено
// справжній файл і його шлях записано в hero_photo_path, сторінка бере його, і
// правити код для цього не треба.
export const HERO_PLACEHOLDER = '/wedding/hero-placeholder.jpg';
