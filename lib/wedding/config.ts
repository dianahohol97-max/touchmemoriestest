// Пайлот весільної сторінки — спільні межі та типи (Діана, 16.09.2026).
//
// Тут лежать числа, які мусять збігатися на клієнті й на сервері. Якщо ліміт
// живе у двох місцях окремо, вони розходяться: клієнт пропускає файл, сервер
// його відхиляє, і гість бачить помилку вже після очікування на завантаження.

/** Бакет саме для весільних фото. */
//
// Навмисно НЕ order-files: там файли самознищуються через 90 днів, бо це
// матеріали до замовлення, які після друку не потрібні. Весільні фото живуть
// стільки, скільки схоче пара, тож автовидалення над ними стояти не може.
// Бакет приватний, і жодної політики на storage.objects для нього немає:
// покласти й прочитати може лише службова роль, тобто наші роути.
export const WEDDING_BUCKET = 'wedding-photos';

/** Скільки файлів гість надсилає за один раз. */
export const MAX_FILES_PER_BATCH = 20;

/**
 * Межа на одне ФОТО до стиснення.
 *
 * Гість вибирає з галереї те, що зняв телефон, і 15 МБ покривають і HEIC з
 * iPhone, і HDR з Android. Стиснення відбувається до відправки, тож у бакет
 * лягає вже щось близько мегабайта.
 */
export const MAX_IMAGE_BYTES = 15 * 1024 * 1024;

/**
 * Межа на одне ВІДЕО.
 *
 * Стиснути відео на клієнті, як ми робимо з фото, неможливо: браузер не вміє
 * перекодовувати його ані швидко, ані надійно, тож ролик летить оригіналом.
 * 200 МБ — це приблизно три хвилини 1080p або сорок секунд 4K, чого для
 * весільного вітання досить, а менша межа відрізала б половину роликів із
 * сучасних телефонів. Збігається з file_size_limit бакета.
 */
export const MAX_VIDEO_BYTES = 200 * 1024 * 1024;

/** Довша сторона після стиснення. */
//
// 2560 достатньо, щоб з фото потім надрукувати розворот фотокниги, і вдвічі
// менше за оригінал з телефона за обсягом. Весільний Wi-Fi цього не помітить,
// а от оригінали на 8 МБ помітить одразу.
export const MAX_LONG_EDGE = 2560;

/** Якість JPEG після стиснення. */
export const JPEG_QUALITY = 0.85;

/** Типи зображень, які приймає і бакет, і роут. */
//
// HEIC тут немає навмисно: він перетворюється на JPEG ще в браузері гостя, тож
// у бакет доходить уже картинкою.
export const ALLOWED_IMAGE_MIME = ['image/jpeg', 'image/png', 'image/webp'] as const;

/** Типи відео. */
//
// quicktime — це .mov, тобто те, що знімає кожен iPhone. Без нього половина
// гостей отримала б відмову на найзвичайнісінькому ролику.
export const ALLOWED_VIDEO_MIME = ['video/mp4', 'video/quicktime', 'video/webm'] as const;

export const ALLOWED_MIME = [...ALLOWED_IMAGE_MIME, ...ALLOWED_VIDEO_MIME] as const;

export const isVideoMime = (mime: string) => mime.startsWith('video/');

/** Скільки живе підписане посилання на перегляд відео. */
//
// Дві години покривають і вечір, і те, що сторінка лишається відкритою. Коротше
// означало б, що ролик перестає програватися просто під час перегляду; довше —
// що посилання, яке кудись витекло, живе зайве.
export const VIDEO_URL_TTL_SECONDS = 2 * 60 * 60;

/** Як часто сторінка питає про нові фото. */
//
// Опитування, а не realtime: підписка тримає сокет відкритим у кожного гостя,
// а весілля — це десятки телефонів у поганій мережі. П'ятнадцять секунд на
// весіллі непомітні, зате сторінка переживає втрату зв'язку без перепідключень.
export const GALLERY_POLL_MS = 15_000;

/** Скільки фото віддається за одну сторінку галереї. */
export const GALLERY_PAGE_SIZE = 48;

/** Скільки фото лягає в один архів для пари. */
//
// Півтори сотні знімків — це приблизно 150 МБ, які функція встигає зібрати й
// віддати в межах своїх обмежень. Одним архівом на все весілля не віддати:
// пів тисячі фото це близько 500 МБ, і така відповідь не вкладається ані в
// памʼять, ані в час. Число можна піднімати, поки архіви збираються надійно.
export const ALBUM_BATCH_SIZE = 150;

/**
 * Кольори весільної сторінки.
 *
 * Бордо — головний акцент, коричневий — текст, білий — імена поверх фото.
 * Лежать тут, а не розсипані по компонентах, бо наступна пара цілком може
 * захотіти свій колір, і тоді міняти доведеться одне місце, а не шість.
 *
 * Імена в шапці лишаються білими навіть у бордовій схемі, і це не недогляд:
 * вони стоять поверх фотографії, а кольоровий текст на строкатому тлі
 * читається гірше за білий із тінню, хай яким вдалим був би колір сам по собі.
 */
export const WEDDING_COLORS = {
  /** Бордо — кнопки, заголовки, акценти. */
  accent: '#6E1F2E',
  accentHover: '#571825',
  /** Коричневий — основний текст. */
  text: '#4A4038',
  /** Приглушений коричневий — другорядні написи. */
  muted: '#8A7A6B',
} as const;

export interface WeddingEvent {
  id: string;
  slug: string;
  couple_names: string;
  event_date: string;
  hero_photo_path: string | null;
}

export interface WeddingPhoto {
  id: string;
  guest_name: string | null;
  width: number | null;
  height: number | null;
  created_at: string;
  mime_type: string;
  duration_seconds: number | null;
  /** Відеопобажання з книги, а не звичайний ролик із вечора. */
  is_wish: boolean;
  /**
   * Підписане посилання на сам ролик, лише для відео.
   *
   * Відео НЕ йде через наш роут, на відміну від картинок: програвачеві
   * потрібні часткові запити (range), щоб перемотувати й не тягнути сто
   * мегабайтів заради перших секунд. Сховище вміє це саме, а наша функція
   * віддавала б файл цілком і платила б за кожен перегляд.
   */
  video_url?: string | null;
}

/**
 * Адреса, якою сторінка показує плитку в сітці. Її ж оптимізує next/image.
 *
 * Для відео цей самий роут віддає кадр-обкладинку, а не ролик, тож сітці не
 * треба знати, на що вона дивиться: вона завжди питає одну адресу.
 */
export const photoUrl = (id: string) => `/api/wedding/photo/${id}`;

/** Адреса фото пари для шапки. */
export const heroUrl = (slug: string) => `/api/wedding/${slug}/hero`;

/** Адреса однієї порції архіву для пари. */
export const albumZipUrl = (token: string, offset: number) =>
  `/api/wedding/album/${token}/zip?offset=${offset}`;

