/**
 * Палітра макета — кольори, які вже є у проєкті клієнта.
 *
 * Панель тексту пропонувала вісім фіксованих кольорів плюс піпетку, і жоден з
 * них не мав стосунку до обраного шаблону. Клієнт бере готовий журнал у
 * теплій пудровій гамі, додає підпис і тикає в перший-ліпший свотч — макет
 * розсипається на дві незалежні палітри, а помічає це вже друкарня. Піпетка
 * теоретично рятувала, але вимагала знати HEX кольору, який ти ніде не бачиш.
 *
 * Тому перед фіксованими свотчами показуємо ті кольори, що вже працюють у
 * цьому макеті: фон і підписи обкладинки, фон поточної сторінки, кольори
 * решти текстів. Це не новий дизайн і не обмеження — фіксовані вісім і піпетка
 * лишаються на місці, просто рідні кольори тепер стоять першими.
 *
 * Джерела свідомо не хардкодяться на id шаблону: клієнт застосовує шаблон, а
 * далі редагує його годинами. Читаємо фактичний стан макета, тож палітра
 * лишається правдивою і після ручних правок, і для макета, зібраного з нуля.
 */

/**
 * Зводить колір до нижнього регістру #rrggbb або повертає null.
 *
 * Приймає і скорочений #rgb (шаблони пишуть по-різному), відкидає порожні
 * значення, назви кольорів і градієнти — свотч має бути суцільним кольором,
 * інакше кнопка малюється прозорою і клієнт не розуміє, чому нічого не сталося.
 */
export function normalizeHex(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const v = value.trim().toLowerCase();
  if (/^#[0-9a-f]{6}$/.test(v)) return v;
  if (/^#[0-9a-f]{3}$/.test(v)) return `#${v[1]}${v[1]}${v[2]}${v[2]}${v[3]}${v[3]}`;
  // #rrggbbaa — беремо кольорову частину, прозорість для тексту не потрібна.
  if (/^#[0-9a-f]{8}$/.test(v)) return v.slice(0, 7);
  return null;
}

export interface PaletteSource {
  /** Фон обкладинки (coverState.printedBgColor). */
  coverBgColor?: unknown;
  /** Підписи на обкладинці — передній і задній бік. */
  coverTexts?: { color?: unknown }[];
  /** Фон поточної сторінки. Свотч, рівний йому, відкидається — текст був би невидимий. */
  pageBgColor?: unknown;
  /** Тексти поточної сторінки (розвороту) — головне джерело палітри шаблону. */
  pageTexts?: { color?: unknown }[];
  /** Тексти решти сторінок — щоб підпис на новій сторінці збігався з попередніми. */
  otherTexts?: { color?: unknown }[];
  /** Кольори, які вже є у фіксованому наборі — дублювати їх немає сенсу. */
  exclude?: string[];
  /** Скільки свотчів показати. Один ряд панелі — шість. */
  max?: number;
}

/**
 * Збирає палітру макета у порядку корисності.
 *
 * Спершу тексти поточної сторінки — саме їх клієнт бачить перед собою і саме
 * до них має пасувати новий підпис. Далі обкладинка, бо вона задає тон усій
 * книзі. Фони йдуть після текстів: як колір підпису вони придатні (темний фон
 * обкладинки чудово читається на світлій сторінці), але це вже другий ешелон.
 * Тексти інших сторінок замикають список.
 */
export function projectPalette(src: PaletteSource): string[] {
  const max = src.max ?? 6;
  const pageBg = normalizeHex(src.pageBgColor);

  const seen = new Set<string>();
  for (const c of src.exclude || []) {
    const n = normalizeHex(c);
    if (n) seen.add(n);
  }
  // Колір фону поточної сторінки як колір тексту дав би невидимий підпис.
  if (pageBg) seen.add(pageBg);

  const out: string[] = [];
  const push = (value: unknown) => {
    if (out.length >= max) return;
    const n = normalizeHex(value);
    if (!n || seen.has(n)) return;
    seen.add(n);
    out.push(n);
  };

  for (const t of src.pageTexts || []) push(t?.color);
  push(src.coverBgColor);
  for (const t of src.coverTexts || []) push(t?.color);
  for (const t of src.otherTexts || []) push(t?.color);

  return out;
}
