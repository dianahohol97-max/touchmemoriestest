import type { CSSProperties } from 'react';

/**
 * Читабельність тексту поверх фото.
 *
 * НАВІЩО. Білий підпис лягає на світлу ділянку знімка і зникає, темний — на
 * темну. На TM-001257 це трапилось майже на кожному розвороті: «INNA & SERHII
 * LOVE STORY» на світлій стіні, «УКРАЇНСЬКА КРАСА…» на зеленому листі, «Від
 * перших спільних пригод…» на світлому фоні. Клієнт не має інструмента, щоб це
 * виправити, крім як вручну підбирати колір, а на екрані ноутбука різниця
 * помітна значно гірше, ніж на глянцевому папері.
 *
 * Підкладка вмикається однією дією і вирішує обидва випадки: світла — під
 * темний текст, темна — під світлий. Окремо є мʼяка тінь, коли підкладка
 * зіпсувала б композицію, а контрасту бракує зовсім трохи.
 *
 * ОДИН МОДУЛЬ НА ВСІХ. Стилі імпортують і редактор, і рендерер друку — з тієї ж
 * причини, з якої так зроблено з автопідбором кегля в text-fit.ts: якщо підкладка
 * вималюється у редакторі й не вималюється у файлі (або навпаки), клієнт отримає
 * не те, що бачив, і це найгірший тип помилки в друці.
 *
 * Відсутнє значення означає «нічого не малювати» — тож усі раніше збережені
 * макети рендеряться байт-у-байт як досі.
 */
export type TextPlate = 'light' | 'dark' | 'shadow';

/** Фон і скруглення для контейнера текстового блока. */
export function plateBoxStyle(plate: TextPlate | undefined | null): CSSProperties {
    if (plate === 'light') return { background: 'rgba(255,255,255,0.72)', borderRadius: 6 };
    if (plate === 'dark') return { background: 'rgba(0,0,0,0.45)', borderRadius: 6 };
    return {};
}

/**
 * Тінь під літерами. Для режиму 'shadow' — виражена, щоб реально тримати текст
 * на строкатому фоні; у решті випадків лишається та сама ледь помітна тінь,
 * яку рендерер друку малював завжди.
 */
export function plateTextShadow(plate: TextPlate | undefined | null): string {
    if (plate === 'shadow') return '0 2px 6px rgba(0,0,0,0.55), 0 0 2px rgba(0,0,0,0.4)';
    return '0 1px 2px rgba(0,0,0,0.2)';
}
