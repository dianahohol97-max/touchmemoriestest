/**
 * Чи зібрався макет ПОВНІСТЮ — читання відповіді сервісу рендеру.
 *
 * Питання коштує дорого, бо саме на цій відповіді тримається прибирання
 * старих файлів. Поки сервіс помирав на першій невдалій сторінці, «прийшла
 * відповідь 200» і «макет зібрався весь» означали те саме, і код міг
 * перевіряти просто `uploaded.length`. Відколи сервіс переживає невдалу
 * сторінку й іде далі, 200 приходить і на пʼять аркушів із сімнадцяти — а
 * прибирання за старою умовою знесло б учорашній цілий макет заради них.
 *
 * Тому неповний набір ніколи не вважається повним, і сумнів тлумачиться на
 * користь «неповний»: залишити зайві старі файли можна виправити руками,
 * а видалені — ні.
 */

export type RenderServiceDetail = {
    ok?: unknown;
    uploaded?: unknown;
    failed?: unknown;
};

/** Скільки аркушів сервіс не подужав. Невідоме читається як нуль. */
export function failedSpreadCount(detail: RenderServiceDetail | null | undefined): number {
    const failed = detail?.failed;
    return Array.isArray(failed) ? failed.length : 0;
}

/**
 * Повний макет — це `ok` не `false` І жодного запису про невдалий аркуш.
 *
 * Обидві умови потрібні окремо. Старіший деплой сервісу не надсилає ні `ok`,
 * ні `failed`, і для нього відповідь вважається повною, як і було до цих змін.
 * Новіший надсилає обидва поля, і кожного з них досить, щоб визнати макет
 * неповним.
 */
export function isRenderComplete(detail: RenderServiceDetail | null | undefined): boolean {
    if (!detail) return false;
    if (detail.ok === false) return false;
    return failedSpreadCount(detail) === 0;
}
