/**
 * Коли фото стає м'яким на друці — одне правило на весь проєкт.
 *
 * Число 91 обрала Діана і воно не кругле навмисно (гоча 6 у CLAUDE.md): нижче
 * нього мʼякість видно на надрукованій сторінці, вище — попередження було б
 * шумом на кожному другому знімку.
 *
 * ЧОМУ ОКРЕМИЙ МОДУЛЬ. Той самий поріг уже стояв у трьох місцях окремими
 * числами: у редакторі вільних слотів, у конструкторі фотодруку і тепер ще
 * знадобився заявці з дизайнером. Три копії одного числа розходяться рано чи
 * пізно, і розходження тут означає, що на одній сторінці фото «нормальне», а
 * на іншій те саме фото «мʼяке».
 *
 * Сама арифметика DPI лишається на місці виклику, бо вона різна: у редакторі
 * рахують проти розміру слота в міліметрах, у фотодруці — проти площі в
 * сантиметрах, у заявці — проти цілої сторінки. Спільне тут рівно те, що
 * розходиться: межі.
 */

/** Нижче цього фото друкується помітно мʼяким. */
export const DPI_WARN = 91;

/** Нижче цього мʼякість уже впадає в око будь-кому. */
export const DPI_BAD = 70;

export type DpiLevel = 'ok' | 'warn' | 'bad';

/** Рівень за готовим DPI. `null` — число безглузде, показувати нема чого. */
export function dpiLevel(dpi: number): DpiLevel | null {
    if (!Number.isFinite(dpi) || dpi <= 0) return null;
    if (dpi >= DPI_WARN) return 'ok';
    if (dpi >= DPI_BAD) return 'warn';
    return 'bad';
}

/** Скільки DPI дають ці пікселі на цій довжині в міліметрах. */
export function dpiFor(pixels: number, mm: number): number {
    if (!(pixels > 0) || !(mm > 0)) return 0;
    return pixels / (mm / 25.4);
}
