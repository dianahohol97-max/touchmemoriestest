/**
 * Одна фраза попередження про відсутні файли для друку — на всю систему.
 *
 * ЧОМУ ЦЕ ОКРЕМИЙ МОДУЛЬ. Попередження писали два незалежні механізми різними
 * словами. Крон missing-print-files і кнопка «позначити» писали «файли для
 * друку не завантажились», і саме цю фразу знає решта системи: список
 * замовлень підсвічує такий рядок червоним, KeyCRM скорочує його до «Немає
 * макета з конструктора», щоденне зведення його рахує. Аудит у render-order
 * писав власну фразу «Нема файлів для друку», і її не знав ніхто: 34
 * замовлення стояли позначені й були невидимі для всіх трьох екранів.
 *
 * До того ж у самому аудиті маркер («бракує файлів для друку») не збігався з
 * текстом, який він писав, тож перевірка «вже позначено» не спрацьовувала й
 * повторний запуск дописував те саме речення ще раз — так вийшли дублі в
 * TM-001202, TM-001260, TM-001285 і TM-001291. Тому текст і маркер тут одне:
 * рядок будується з тієї самої константи, за якою його потім упізнають.
 */

export const PRINT_WARNING_MARKER = 'файли для друку не завантажились';

/**
 * Фрази, якими це саме попередження писали раніше.
 *
 * Нових таких рядків не пишемо — вони потрібні лише для того, щоб упізнати й
 * прибрати те, що вже лежить у базі.
 */
export const LEGACY_PRINT_WARNING_MARKERS = ['Нема файлів для друку', 'дизайн не збережено'];

/** Чи несе примітка попередження про відсутні файли, хоч би яким із формулювань. */
export function hasPrintWarning(notes: string | null | undefined): boolean {
    const text = String(notes || '');
    if (!text) return false;
    return text.includes(PRINT_WARNING_MARKER) || LEGACY_PRINT_WARNING_MARKERS.some(m => text.includes(m));
}

/**
 * Примітка без попередження про друк — решта тексту недоторкана.
 *
 * Прибирається рядок цілком, бо попередження завжди займає свій рядок і
 * ставиться на початок. Порожні рядки, що лишилися від нього, сходяться в
 * один, щоб бриф не роз'їжджався.
 */
export function stripPrintWarning(notes: string | null | undefined): string {
    const text = String(notes || '');
    if (!text) return '';
    return text
        .split('\n')
        .filter(line => !(line.includes(PRINT_WARNING_MARKER) || LEGACY_PRINT_WARNING_MARKERS.some(m => line.includes(m))))
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trim();
}

/**
 * Рядок попередження для примітки замовлення.
 *
 * Короткий навмисне: він потрапляє у вузьку колонку списку замовлень і в
 * коментар менеджера в KeyCRM (Діана, 11.08.2026, тричі про завеликі
 * коментарі). Назви позицій лишаються, бо менеджеру треба знати, якого саме
 * товару бракує макета.
 */
export function printWarningLine(missing: string[]): string {
    const what = missing.length ? `: ${missing.join(', ')}` : '';
    return `⚠️ УВАГА: ${PRINT_WARNING_MARKER}${what} — макет з конструктора відсутній. Зв'яжіться з клієнтом.`;
}

/**
 * Чи це замовлення з дизайнером, яке просто ще не зверстали.
 *
 * Правило з одного рядка, але помилитися в ньому дорого в обидва боки: зайва
 * мітка знецінює всі інші, а пропущена ховає справжню втрату. Тому воно тут,
 * поряд із самим текстом попередження, і накрите тестами.
 *
 * `with_designer` каже, що макет збираємо МИ, а не клієнт, — отже питати з
 * нього макет із конструктора нема за що. Наявність його фото каже, що свою
 * частину він виконав. Замовлення з дизайнером без жодного файлу — це все ще
 * справжня біда, і воно мітку отримає.
 *
 * Чого тут НЕМАЄ і чому: призначеного дизайнера. Дизайнера призначають після
 * оплати, інколи через години, а аудит біжить одразу по ній — у тому вікні
 * умова не виконувалася ніколи, і кожне свіжо оплачене замовлення з
 * дизайнером діставало «макет з конструктора відсутній» (Діана, 17.09.2026:
 * TM-001317, TM-001318, TM-001332, TM-001336, TM-001338 — усі зі своїми фото
 * на місці).
 */
export function isDesignerInFlight(order: { with_designer?: unknown }, hasCustomerFiles: boolean): boolean {
    return Boolean(order?.with_designer) && hasCustomerFiles;
}
