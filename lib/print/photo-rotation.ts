/**
 * Геометрія повороту фотографії у друкованій рамці.
 *
 * Замовлення 14217: клієнт написав, що всі фото, які він повернув у
 * конструкторі, вийшли з друку з чорною рамкою — і полароїди так само. З
 * усього замовлення нормальними виявилися 24 знімки.
 *
 * Причина не в друкарні. Конструктор рахував кадр так, ніби повороту немає:
 * джерело обрізалося під пропорції рамки, і рівно такий прямокутник малювався
 * у вже повернутій системі координат. Після повороту на 90° він лягав упоперек
 * — широка смуга всередині вузького полотна. Зверху й знизу лишалися пікселі,
 * яких не торкнулася жодна операція малювання.
 *
 * Далі спрацьовувало те, що робить цю помилку невидимою до самого друку.
 * Незаймане полотно прозоре, а JPEG прозорості не має, тож canvas.toBlob
 * зводить його на ЧОРНЕ. У прев'ю під зображенням лежить білий div, і клієнт
 * бачив білі поля — тобто макет на екрані й файл для друку розходилися саме
 * тим кольором, який найдорожче побачити вперше на папері.
 *
 * Та сама пара помилок била і по зменшенню (zoom < 1): вікно джерела стає
 * більшим за саме фото, drawImage домальовує решту прозорим, і поля знову
 * чорні. Тому виправлень тут два і вони незалежні: ця геометрія прибирає самі
 * поля там, де їх не мало бути, а біла заливка полотна перед малюванням
 * гарантує, що будь-яке неторкнуте місце лишиться білим, а не чорним.
 *
 * Модуль спільний для прев'ю і для рендера навмисно. Раніше кожна з чотирьох
 * точок рахувала покриття власною формулою, і розбіжність між екраном і
 * файлом ніде не було видно.
 */

/** Кут у межах 0…359, яким би не прийшло значення. */
export function normalizeRotation(rotation?: number | null): number {
    const raw = Number(rotation);
    if (!Number.isFinite(raw)) return 0;
    return ((raw % 360) + 360) % 360;
}

/**
 * Чи міняє поворот осі місцями.
 *
 * Тільки 90° і 270°. Поворот на 180° осей не міняє, тож для нього нічого
 * перераховувати не треба — і саме тому в скаргах фігурують «перевернуті
 * набік», а не «догори ногами».
 */
export function isQuarterTurn(rotation?: number | null): boolean {
    const deg = normalizeRotation(rotation);
    return deg === 90 || deg === 270;
}

/**
 * Прямокутник, який фото має заповнити, — у ВЛАСНИХ осях фото, до повороту.
 *
 * Для чверті обороту ширина й висота рамки міняються місцями: те, що стане
 * висотою відбитка, для фото ще ширина. Малювати треба саме цей прямокутник,
 * тоді після повороту він накриє рамку точно, без полів.
 */
export function fitBoxForRotation(
    frameW: number,
    frameH: number,
    rotation?: number | null,
): { w: number; h: number } {
    return isQuarterTurn(rotation) ? { w: frameH, h: frameW } : { w: frameW, h: frameH };
}

/**
 * Множник до objectFit:contain, щоб повернуте фото покрило рамку.
 *
 * Прев'ю показує фото як contain у рамці frameW×frameH і масштабує його
 * трансформою. Без урахування повороту цей множник рахувався по неповернутій
 * рамці, тож на екрані повернуте фото теж не покривало кадр — просто поля були
 * білі й виглядали як задум.
 *
 * imgAR нуль, від'ємний або NaN означає, що розмірів фото ще немає: тоді
 * повертаємо 1 і кадр лишається як є, поки розміри не приїдуть.
 */
export function coverScaleForRotation(
    frameW: number,
    frameH: number,
    imgAR: number,
    rotation?: number | null,
): number {
    if (!(frameW > 0) || !(frameH > 0)) return 1;
    if (!Number.isFinite(imgAR) || !(imgAR > 0)) return 1;

    const frameAR = frameW / frameH;
    // objectFit: contain — довша сторона впирається в рамку.
    const containW = imgAR > frameAR ? frameW : frameH * imgAR;
    const containH = imgAR > frameAR ? frameW / imgAR : frameH;
    if (!(containW > 0) || !(containH > 0)) return 1;

    const need = fitBoxForRotation(frameW, frameH, rotation);
    return Math.max(need.w / containW, need.h / containH);
}
