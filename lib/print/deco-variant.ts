/**
 * Фізичний розмір оздоблення обкладинки з підпису варіанта.
 *
 * Варіанти зберігаються рядком так, як їх бачить клієнт: «90×50 золотий»,
 * «250×70 срібний», «100×100 мм», «Ø145 мм», «197×197 мм». Число в цьому
 * рядку — єдине місце, де взагалі записано, якого розміру буде вставка, бо
 * далі по конвеєру їде саме він.
 *
 * ЧОМУ ЦЕ ОКРЕМИЙ МОДУЛЬ. Розбір жив у трьох місцях із трьома різними
 * регулярками й трьома різними запасними значеннями: у конструкторі
 * обкладинки, у серверному рендері обкладинки й ніде — у генераторі файлів
 * для лазера, який просто нічого не розбирав. Через це один і той самий
 * варіант давав на прев'ю один розмір, на макеті обкладинки інший, а у файлі
 * для майстерні третій. TM-001288 замовив металеву вставку 90×50, а в друк
 * пішов квадрат 60×60.
 *
 * Запасне значення НЕ вшите: кожен виклик передає своє, бо для металу
 * розумний запас це 90×50, а для акрилу 100×100, і мовчазна підміна одного
 * іншим — саме та помилка, від якої цей модуль і рятує.
 */

export interface DecoVariantDims {
    w: number;
    h: number;
    /** Кругла вставка (підпис «Ø145 мм»), а не прямокутна. */
    round: boolean;
}

/**
 * Діаметр або сторони у міліметрах.
 *
 * Приймає і латинську x, і кириличну х, і знак ×, з пробілами навколо або без
 * них — підписи варіантів набирали руками в різний час, і всі три написання в
 * базі реально зустрічаються.
 */
export function parseDecoVariantMm(
    variant: string | null | undefined,
    fallback: DecoVariantDims,
): DecoVariantDims {
    const s = String(variant ?? '').trim();
    if (!s) return { ...fallback };

    const circle = s.match(/[Øø⌀]\s*(\d+(?:[.,]\d+)?)/);
    if (circle) {
        const d = Number(circle[1].replace(',', '.'));
        if (d > 0) return { w: d, h: d, round: true };
    }

    const pair = s.match(/(\d+(?:[.,]\d+)?)\s*[хx×]\s*(\d+(?:[.,]\d+)?)/i);
    if (pair) {
        const w = Number(pair[1].replace(',', '.'));
        const h = Number(pair[2].replace(',', '.'));
        if (w > 0 && h > 0) return { w, h, round: false };
    }

    return { ...fallback };
}

/**
 * Імʼя файлу для майстерні за фактичним розміром вставки.
 *
 * Ім'я читає людина за верстатом, тож у ньому має стояти той розмір, який
 * справді треба вигравіювати. Раніше файл звався metal_60x60.jpg завжди, і
 * розмір у назві був не описом, а обіцянкою, якої файл не виконував.
 */
export function decoFileName(prefix: string, dims: DecoVariantDims, ext = 'jpg'): string {
    const num = (n: number) => String(Math.round(n * 10) / 10).replace('.', '_');
    return dims.round
        ? `${prefix}_d${num(dims.w)}.${ext}`
        : `${prefix}_${num(dims.w)}x${num(dims.h)}.${ext}`;
}
