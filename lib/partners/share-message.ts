import { partnerRefLink } from '@/lib/partners/referral-link';

/**
 * Готовий текст, яким менеджер віддає партнеру його посилання.
 *
 * НАВІЩО ГОТОВИЙ ТЕКСТ, А НЕ ПРОСТО ПОСИЛАННЯ. Менеджер домовляється в
 * інстаграм-директі, і саме там угода або закривається, або зависає. Коли
 * треба самому придумати, як пояснити умови, повідомлення пишеться довго і
 * щоразу інакше — а помилитися в ньому легко саме в тому місці, де це коштує
 * грошей: знижка діє лише на ПЕРШЕ замовлення клієнта, а відсоток партнеру йде
 * з усіх. Один текст на всіх прибирає і затримку, і різнобій.
 *
 * ЧОМУ ТУТ НЕМАЄ ПОСИЛАННЯ НА КАБІНЕТ ПАРТНЕРА. Приватний `cabinet_token`
 * відкриває нарахування й реквізити для виплат без пароля, тож менеджер його не
 * бачить і переслати не може. Партнер отримує кабінет вітальним листом або
 * формою відновлення на /uk/partner/find — тобто завжди на власну пошту.
 */
export function partnerShareMessage(code: string | null | undefined): string {
    const link = partnerRefLink(code);
    return [
        `Вітаю вас і надсилаю персональне посилання для співпраці з touch.memories: ${link}`,
        `Клієнт переходить за ним і бачить знижку вже в кошику, вводити нічого не треба — знижка діє на перше замовлення.`,
        `Вам нараховується відсоток із кожної покупки цієї людини, і далі теж: хто хоч раз замовив за вашим посиланням, лишається за вами назавжди, навіть коли повертається на сайт сам.`,
        `Посилання можна поставити в шапку профілю, кинути в сторіс або надіслати особисто — воно працює скрізь однаково.`,
    ].join('\n\n');
}
