/**
 * Реферальне посилання партнера — в одному місці.
 *
 * Посилання стало головним інструментом партнера 16.09.2026: за ним знижка
 * застосовується сама, і клієнту не треба нічого набирати. Рядок будувався в
 * трьох місцях окремо — у кабінеті партнера, в адмінці й тепер у кабінеті
 * клієнта, — і вже встиг розійтися: у кабінеті код кодується через
 * encodeURIComponent, в адмінці ні. Партнерські коди роблять із назв агенцій,
 * тож бувають кириличними («ПОДОTABB» у живій базі), і незакодований рядок
 * приїжджає побитим, щойно його скопіюють у месенджер.
 */
export const PARTNER_SITE_ORIGIN = 'https://touchmemories.com.ua';

export function partnerRefLink(code: string | null | undefined): string {
    return `${PARTNER_SITE_ORIGIN}/?ref=${encodeURIComponent(String(code ?? '').trim())}`;
}
