/**
 * Перехід за партнерським посиланням: що рахувати і що не рахувати.
 *
 * Логіка тут чиста і без доступу до window — щоб її можна було перевірити
 * тестом, а не здогадками. Бік браузера живе в components/ReferralCapture,
 * бік сервера — у /api/referral/visit, і обидва питають ці самі функції.
 *
 * ДВА РІВНІ ВІДСІВУ, і вони закривають різні речі.
 *
 * Перший — сам факт `?ref=` в адресі. Рахується тільки той захід, у якому код
 * прийшов ПАРАМЕТРОМ, тобто людина справді клацнула партнерське посилання.
 * Далі вона ходить каталогом, товарами й кошиком без цього параметра, і жодна
 * з тих сторінок переходом не вважається. Якби рахувався кожен показ, партнер
 * бачив би не перехід, а глибину перегляду, і число було б завищене вдесятеро
 * на тому самому клієнті.
 *
 * Другий — вікно в добу на код. Одне й те саме посилання відкривають двічі за
 * вечір: з листа й зі збереженої вкладки, з історії браузера, з месенджера,
 * який дописує власний перегляд. Це один перехід однієї людини. Доба вибрана
 * як найкоротший строк, який ще покриває «подивилася вранці, повернулася
 * ввечері»; коротше вікно почало б рахувати ту саму людину двічі, довше —
 * ховало б справді новий візит наступного дня.
 *
 * ЧОГО ТУТ СВІДОМО НЕМАЄ. Відсів не спирається ні на IP, ні на User-Agent, ні
 * на будь-який ідентифікатор відвідувача: таблиця переходів не зберігає
 * персональних даних узагалі, і механізм дедуплікації не має ставати
 * причиною, з якої вони там зʼявляться. Тому памʼять про «цей код уже
 * порахований» лежить у localStorage самого відвідувача, а не в нас.
 *
 * ЧЕСНО ПРО МЕЖУ. Заголовний браузер без localStorage обійде перший рівень, а
 * сервер додає лише короткочасний захист у памʼяті процесу. Тому переходи
 * варто читати поруч із замовленнями, а не як окреме число: конверсія з
 * накрученими переходами впаде і сама про це скаже.
 */

/** Скільки повторні заходи за тим самим кодом не рахуються, у мілісекундах. */
export const VISIT_DEDUP_WINDOW_MS = 24 * 60 * 60 * 1000;

/** Партнерські коди бувають кирилицею — їх генерують із назв агенцій. */
const CODE_RE = /^[A-Za-z0-9А-ЯІЇЄҐа-яіїєґ]{4,16}$/;

/** Ключ у localStorage, під яким лежить час останнього порахованого переходу. */
export function visitStorageKey(code: string): string {
    return `tm_ref_visit:${String(code ?? '').trim().toUpperCase()}`;
}

/** Чи схожий рядок на партнерський код. Та сама перевірка, що й у чекауті. */
export function isVisitCodeShaped(code: string | null | undefined): boolean {
    return CODE_RE.test(String(code ?? '').trim());
}

/**
 * Чи рахувати цей захід переходом.
 *
 * `lastRecordedAt` — те, що лежить у сховищі (рядок, число або null). Зіпсоване
 * значення трактується як «не рахували»: втратити перехід гірше, ніж порахувати
 * зайвий, бо перше коштує партнеру грошей, а друге — точності числа.
 */
export function shouldRecordVisit(
    lastRecordedAt: string | number | null | undefined,
    now: number = Date.now(),
    windowMs: number = VISIT_DEDUP_WINDOW_MS,
): boolean {
    if (lastRecordedAt === null || lastRecordedAt === undefined || lastRecordedAt === '') return true;
    const ts = Number(lastRecordedAt);
    if (!Number.isFinite(ts) || ts <= 0) return true;
    // Час із майбутнього — переставлений годинник або чужий запис. Рахуємо.
    if (ts > now) return true;
    return now - ts >= windowMs;
}

/**
 * Сторінка входу, приведена до вигляду, який можна зберігати.
 *
 * Лишається тільки шлях: параметри адреси несуть і сам код, і чужі мітки
 * (utm_*, fbclid, gclid), а рекламні мітки цілком можуть містити ідентифікатор
 * конкретного показу — тобто рівно те, чого в цій таблиці бути не повинно.
 * Довжина обрізається, бо шлях приходить від клієнта.
 */
export function normalizeLandingPath(raw: string | null | undefined): string | null {
    const value = String(raw ?? '').trim();
    if (!value) return null;
    // Абсолютні адреси й протоколи відкидаємо: сюди має приходити шлях.
    const withoutQuery = value.split('?')[0].split('#')[0];
    if (!withoutQuery.startsWith('/')) return null;
    return withoutQuery.slice(0, 200);
}
