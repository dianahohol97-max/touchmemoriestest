-- ЦЮ МІГРАЦІЮ НЕ ЗАСТОСОВАНО. Вона чекає на рішення Діани.
--
-- Тому вона лежить у docs/proposed-migrations, а НЕ в supabase/migrations:
-- та тека — запис того, що вже накочено на базу, і незастосований файл у ній
-- рано чи пізно накотили б наосліп. Коли рішення буде, файл переїжджає в
-- supabase/migrations і застосовується звідти.
--
-- Анонімна вставка замовлення більше не може заявити, що гроші вже отримані.
--
-- ЩО ЗАРАЗ. Політика «Customers create orders» дозволяє INSERT у public.orders
-- будь-кому, з `with check (true)`. Це не помилка налаштування: два публічні
-- потоки вставляють замовлення ПРЯМО З БРАУЗЕРА, без серверного маршруту —
-- app/[locale]/order/page.tsx (замовлення з дизайнером) і
-- app/[locale]/order/magazine-text-brief/page.tsx (бриф на текст журналу).
-- За тридцять днів це половина всіх замовлень сайту: 52 зі 101.
--
-- ЧОГО НЕМАЄ. Читання й оновлення закриті: клієнт бачить лише свої замовлення,
-- оновлювати може дизайнер або адміністратор. Дірка лише на вставці.
--
-- ЧИМ ЦЕ НЕБЕЗПЕЧНО. `with check (true)` не обмежує ЗНАЧЕННЯ. Підроблений
-- запит може створити замовлення з payment_status = 'paid', paid_amount на
-- будь-яку суму і paid_at — і воно виглядатиме для команди й для вивантаження
-- в KeyCRM як оплачене. Далі його візьмуть у виробництво і відправлять.
--
-- ЧИ СТАЛОСЯ. Ні. На 16.09.2026 у базі НЕМАЄ жодного замовлення з
-- payment_status = 'paid' без рахунку Monobank — ні серед замовлень з
-- дизайнером (0 зі 133), ні взагалі. Дірка відкрита, але нею не скористалися.
--
-- ЩО РОБИТЬ ЦЯ МІГРАЦІЯ. Вставка лишається дозволеною, але рядок не може
-- заявляти про гроші: статус оплати тільки 'pending', отримані суми нульові
-- або порожні, дати платежу немає, і рядок не може вдавати дзеркало з CRM.
-- Ці значення обидва потоки і так ставлять саме такими — перевірено за
-- payload обох вставок, тож жодна легальна вставка не відхиляється.
--
-- ЧОГО ЦЯ МІГРАЦІЯ НЕ ЛІКУЄ. Сума замовлення (`total`) і далі приходить з
-- браузера: у потоці з дизайнером вона береться з sessionStorage, який
-- клієнт контролює. Політика не може знати правильну ціну — її може знати
-- лише сервер, який перерахує кошик, як це робить /api/orders/submit.
-- Тобто це запобіжник, а не рішення; рішення — перенести вставку на сервер.

drop policy if exists "Customers create orders" on public.orders;

create policy "Customers create orders"
on public.orders
for insert
with check (
    coalesce(payment_status, 'pending') = 'pending'
    and coalesce(paid_amount, 0) = 0
    and coalesce(cod_received_at::text, '') = ''
    and paid_at is null
    and coalesce(source, 'site') <> 'keycrm'
);
