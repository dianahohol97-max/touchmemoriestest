## Спосіб третій: глянцевий журнал у репортажному настрої

Якщо книга здається надто врочистою, той самий матеріал добре лягає в журнал. Він легший за вагою і за настроєм, тримає більше тексту на сторінці й виглядає як випуск про твою поїздку, а не як сімейна реліквія.

