## Спосіб перший: паперовий альбом із відбитками

Найстаріший варіант нікуди не подівся і досі працює. Ви друкуєте від тридцяти до шістдесяти кадрів і складаєте їх у альбом руками, підписуючи те, що вважаєте за потрібне.

Сильна сторона тут у тактильності й у повній свободі: можна вкласти квиток, чек із кав''ярні, засушений листок. Слабка сторона в тому, що така робота вимагає вечора або двох, і саме через це альбом найчастіше лишається купкою конвертів із фотолабораторії.

## Спосіб другий: тревелбук про одну поїздку

Тревелбук вирішує ту саму задачу, але замість ручної роботи пропонує зібрати книгу на екрані й отримати готовий результат поштою. Кадри стають розворотами, розвороти — послідовністю, і поїздка читається так, як вона відбувалася.

[Тревелбук](/uk/catalog/travelbook-20x30) ми збираємо під конкретну історію: ви самі вирішуєте, що ставити на обкладинку і в якому порядку йдуть дні. Формат добре тримає одну подорож цілком, і саме в цьому його сила — книга про одну поїздку читається краще за збірник про п''ять.

Окремо варто сказати про підписи. Дві-три фрази під розворотом про те, що там відбувалося, через п''ять років коштують більше за самі знімки, бо деталі забуваються першими.

## Спосіб третій: глянцевий журнал у репортажному настрої

Якщо книга здається надто врочистою, той самий матеріал добре лягає в журнал. Він легший за вагою і за настроєм, тримає більше тексту на сторінці й виглядає як випуск про вашу поїздку, а не як сімейна реліквія.

Глянцевий журнал починається від 525 ₴, і його часто роблять серією: по одному випуску на подорож, які потім стоять на полиці рядком. Для тих, хто їздить часто, це виявляється практичнішим за одну велику книгу, куди все одно все не влізе.

## Спосіб четвертий: дрібні формати, які лишаються на видноті

Книгу треба взяти з полиці, а магніт на холодильнику дивиться на вас сам. Набір фотомагнітів із поїздки працює саме тому, що не потребує жодного зусилля, щоб про нього згадати.

Сюди ж належить постер з одного сильного кадру і зоряна карта неба над тим місцем і тією датою, які для вас щось означають. Карта формату A4 коштує 350 ₴, A3 — 450 ₴, і більший розмір має сенс тоді, коли вона вішається на стіну у вітальні.

## Спосіб п''ятий: порядок у файлах і друга копія

Найменш романтичний спосіб виявляється найважливішим, бо без нього всі попередні одного дня не спрацюють. Одразу після повернення варто скласти кадри поїздки в окрему теку з назвою у форматі «рік — місце» і видалити явні дублі, поки ще пам''ятаєте, який із трьох кадрів був вдалим.

Друга копія має лежати фізично в іншому місці: зовнішній диск удома, якщо основне сховище хмарне, або хмара, якщо основне сховище домашнє. Одна копія не є копією взагалі, і переконуються в цьому зазвичай після того, як телефон уже впав у воду.

