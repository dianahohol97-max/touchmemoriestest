## Чому подарунок після туру працює краще за знижку

Знижка на наступний тур виглядає щедрою, але має вбудований дефект: вона нагадує про себе тільки в момент, коли людина вже вирішила знову їхати. До того вона лежить мертвим рядком у листі, який давно провалився вниз пошти.

Подарунок після туру працює в протилежний бік. Він приходить тоді, коли враження ще свіжі, і саме тому його помічають. Людина щойно повернулася, вона переповнена розповідями і показує фотографії всім підряд — у цей момент будь-що, що продовжує поїздку, потрапляє точно в настрій.

Є ще один бік, який часто недооцінюють. Подарунок, зроблений із власних знімків клієнта, живе у нього вдома роками і щоразу нагадує про поїздку разом із тим, хто її організував. Знижка такого не вміє в принципі.

## Два інструменти, які не заважають один одному

У [партнерській програмі для турагентств](/uk/partnerska-programa-dlya-turagentstv) ці сценарії розведені навмисно, бо вони закривають різні ситуації.

Перший — подарункові сертифікати на тревелбук. Агенція купує їх наперед у партнерському кабінеті зі знижкою 10% і вручає клієнтам після поїздки. Клієнт при цьому отримує повний номінал без жодних додаткових умов, тобто знижка лишається вигодою агенції, а не з''їдається з подарунка. Сертифікат діє три місяці з моменту видачі, і цього вистачає, щоб розібрати фото без поспіху.

Другий — реферальне посилання, яке не потребує жодної закупівлі. Ви отримуєте адресу зі своєю міткою, клієнт переходить за нею і бачить знижку 5% уже в кошику, а агенція отримує 5% від вартості тревелбуків і глянцевих журналів та 3% від вартості решти товарів з кожного оплаченого замовлення.

Обидва інструменти спокійно працюють одночасно. Сертифікати ви вручаєте самі тим, кого хочете виділити, а посилання паралельно приносить винагороду з тих замовлень, які клієнти оформили без сертифіката.

## Що це дає агенції, крім самої винагороди

Найочевидніша вигода — додатковий дохід із замовлень, які ваші клієнти зробили б і без вас. Але вона ж і найменш цікава, бо суми тут скромні й ростуть повільно.

Значно важливіше те, що з''являється привід написати клієнту після туру, не продаючи йому нічого. Лист із подарунком читається інакше, ніж лист із пропозицією, і відкриває розмову, якої без цього не було б узагалі.

Третій ефект стосується самого сервісу. Агенцій, які працюють із тими самими напрямками і тими самими готелями, багато, і відрізнити одну від одної клієнт майже не може. Подарунок після повернення — це та деталь, яку переказують знайомим, бо вона не входить у стандартний набір і тому запам''ятовується.

Жодного власного виготовлення від агенції при цьому не потрібно. Макет, збірку, пакування і доставку беремо ми, а за вами лишається рекомендація і момент вручення.

## Як це виглядає на практиці

Найпростіший робочий сценарій виглядає так. Через кілька днів після повернення менеджер пише клієнту звичайне людське повідомлення з питанням, як минула поїздка, і в тому ж повідомленні передає сертифікат або посилання.

Момент обрано не випадково. Одразу після прильоту людина ще розбирає валізи, а через місяць уже переключилася на роботу. Вікно в три-сім днів після повернення дає найвищий відгук саме тому, що фотографії вже переглянуті, а враження ще не вивітрилися.

Далі від агенції не потрібно нічого. Нарахування видно в партнерському кабінеті, там само вказується карта, і запит на виплату стає доступним, щойно сума досягає 500 грн.

