## Чому сувенір із аеропорту не спрацьовує

Магнітик із назвою міста, брелок і пакетик місцевих солодощів купуються в останню годину перед вильотом, коли сил вибирати вже немає. Вони чесно виконують свою роль рівно до дверей квартири, а далі лягають у шухляду разом із такими самими з попередніх поїздок.

Проблема не в ціні й не в смаку, а в тому, що такий сувенір нічого не розповідає. Він говорить «я тут був», але не говорить, як саме там було, з ким і чому ця поїздка виявилася важливою. Подарунок, який працює довго, будується навколо конкретних спогадів людини, а не навколо географічної назви.

