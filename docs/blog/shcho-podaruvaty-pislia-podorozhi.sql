## Що краще не дарувати

Речі для наступної поїздки — валізи, органайзери, дорожні подушки — виглядають логічно, але насправді говорять про майбутнє, а не про те, що людина щойно пережила. Такий подарунок доречний перед від''їздом, а не після повернення.

Алкоголь і солодощі з тієї самої країни повторюють те, що людина вже привезла собі сама. Рамка для фотографії без самої фотографії перекладає роботу на того, кого ти вітаєш, і в дев''яти випадках із десяти лишається порожньою.

