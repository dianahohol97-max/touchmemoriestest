## Дрібниці, які тримають поїздку на видноті

Не кожен подарунок має бути великим. Фотомагніти з кадрами подорожі працюють на диво довго саме тому, що їх бачать щодня, не докладаючи жодних зусиль. Холодильник відкривають десять разів на добу, і кожного разу людина натрапляє на те море, той гірський перевал або те вечірнє місто.

Зоряна карта закриває іншу потребу. Вона показує небо над конкретним місцем у конкретну ніч, і для поїздки, де була одна визначна дата, це працює точніше за будь-який кадр. Формат A4 коштує 350 ₴, A3 — 450 ₴, і другий виглядає доречніше, коли карта вішається у вітальні, а не стоїть на полиці.

Постер з одного сильного знімка теж не варто скидати з рахунку. Коли з поїздки є один кадр, який усі запам''ятали, він заслуговує на стіну, а не на стрічку в телефоні.

