## Коли обирати сертифікат

Сертифікат виграє скрізь, де клієнтів багато і всі вони різні. Ви не бачили їхніх фотографій, не знаєте, хто з ким їздив і що для них виявилося головним, і будь-яка ваша спроба вгадати буде саме вгадуванням.

Він також виграє за часом. Вручити сертифікат можна в день повернення, поки враження ще не вивітрилися, і при цьому не чекати, доки щось буде зібрано й надруковано. Для агенції це означає передбачуваний процес: купили пачку наперед, видаєте за потребою.

Фінансовий бік теж на його боці. У [партнерському кабінеті](/uk/partnery) сертифікати коштують на 10% дешевше, а клієнт отримує повний номінал без жодних додаткових умов, тобто знижка лишається вигодою агенції й не з''їдається з подарунка. Діє сертифікат три місяці з моменту видачі, і цього достатньо, щоб розібрати фото без поспіху, але замало, щоб про подарунок забути зовсім.

Головний ризик сертифіката чесний і про нього варто знати наперед: частина людей не скористається ним ніколи. Зменшити цю частку допомагає одне нагадування через два-три тижні після вручення.

## Коли обирати готовий тревелбук

Готова книга виграє там, де клієнт один і він для вас особливий. Ювілейна поїздка, весільна подорож, груповий тур, який ви вели самі й знімали разом із усіма, корпоративна група, де у вас є спільний фотоархів.

Сила цього варіанта в моменті вручення. Сертифікат — це обіцянка майбутнього подарунка, а книга вже є, її гортають при вас, і реакція видно одразу. Саме такі історії потім переказують знайомим, і саме вони приводять нових клієнтів.

Умова тут жорстка: у вас мають бути знімки клієнта. Без них персоналізована книга неможлива в принципі, а просити фотографії заздалегідь означає зіпсувати сюрприз. Тому цей варіант природно працює тільки там, де архів утворився сам: групові тури, спільні екскурсії, поїздки з вашим супроводом.

Другий бік — час менеджера. Відбір кадрів і збирання макета вимагають уваги, і на потоці з тридцяти клієнтів на місяць це швидко стає окремою роботою.

## Як більшість агенцій вирішує це на практиці

Робочий підхід полягає в тому, щоб не вибирати взагалі. Сертифікати йдуть усім клієнтам потоком як стандартна частина сервісу, а готова книга — точково, тим кільком за сезон, кого ви справді хочете виділити.

Так закривається і масштаб, і глибина. Потік отримує подарунок, який нічого не коштує за часом, а окремі клієнти отримують те, що переказують далі. Паралельно з цим реферальне посилання приносить винагороду з тих замовлень, які клієнти оформили самостійно, без сертифіката.

Якщо починати з чогось одного, починайте з сертифікатів. Вони вимагають найменше і дають зрозуміти, як ваші клієнти взагалі реагують на таку пропозицію, перш ніж вкладати в неї час менеджера.

