## Скільки коштує подарунок і що з нього повертається

Почнімо з того, що подарунок не обов''язково є витратою взагалі. Реферальне посилання не коштує нічого: ви не викуповуєте нічого наперед, не платите за вхід і нічим не ризикуєте.

З кожного оплаченого замовлення за вашим посиланням агенція отримує 5% від вартості тревелбуків і глянцевих журналів та 3% від вартості решти товарів. Клієнт при цьому не втрачає, а виграє, бо бачить знижку 5% уже в кошику, і промокод йому не потрібен.

Сертифікати влаштовані інакше, і тут витрата справді є. В партнерському кабінеті вони коштують на 10% дешевше номіналу, тобто на пачці сертифікатів номіналом тисяча гривень агенція економить сто гривень із кожного. Клієнт отримує повну тисячу.

## Порахуймо на конкретному прикладі

Візьмемо агенцію, яка проводить п''ятдесят клієнтів за сезон і передає реферальне посилання кожному з них разом із документами.

Припустимо, що замовлення зробить кожен десятий, тобто п''ятеро. Це консервативне припущення для звичайного розсилання і заниження для агенції, яка пише клієнту особисто. Якщо кожне замовлення — це тревелбук або глянцевий журнал, агенція отримує по 5% з кожного, і сума нарахувань за сезон складається саме з цих п''яти замовлень.

Головне тут не разова цифра, а те, що відбувається далі. Клієнт закріплюється за агенцією довічно з першого оплаченого замовлення, тож усі його наступні покупки теж приносять винагороду, навіть коли він приходить на сайт сам і вже без вашого посилання. Через два сезони працюють не п''ятеро клієнтів, а всі, хто колись перейшов за вашою адресою.

Виплата на карту стає доступною, щойно сума нарахувань досягає 500 грн, і запит робиться в тому самому кабінеті, де видно переходи й замовлення.

## Чому варіант із сертифікатом рахується інакше

Сертифікат не окупається нарахуваннями, і робити вигляд, що окупається, було б нечесно. Його вигода лежить в іншій площині.

Перше — це привід написати клієнту після туру, нічого йому не продаючи. Лист із подарунком відкривають і на нього відповідають, тоді як лист із пропозицією наступного туру найчастіше не читають зовсім.

Друге — це те, що подарунок живе в клієнта вдома. Книга з його власних знімків стоїть на полиці роками і щоразу нагадує про поїздку разом із тим, хто її організував. Знижка на наступний тур такого не вміє, бо вона існує тільки у вигляді рядка в пошті.

Третє — це різниця між агенціями, яку клієнт може відчути. Напрямки, готелі й ціни у всіх приблизно однакові, і відрізнити одну агенцію від іншої людина зазвичай не може. Подарунок після повернення не входить у стандартний набір і тому переказується знайомим.

## Що змінює момент вручення

Найбільший вплив на результат має не розмір подарунка, а час, коли його передали. Одразу після прильоту людина розбирає валізи й відсипається, а через місяць уже повністю переключилася на роботу.

Вікно в три-сім днів після повернення працює найкраще, бо фотографії вже переглянуті, а враження ще живі. Саме в цей момент пропозиція зібрати з них книгу потрапляє в настрій, а не сприймається як чергова розсилка.

Другий за важливістю чинник — особисте повідомлення замість масової розсилки. Те саме посилання, надіслане менеджером у звичайному повідомленні з питанням, як минула поїздка, дає незрівнянно більший відгук, ніж той самий текст у загальному листі.

## З чого почати без ризику

Найдешевший спосіб перевірити, чи це працює у вашої агенції, не вимагає жодних вкладень. Подайте заявку на [партнерську програму для турагентств](/uk/partnerska-programa-dlya-turagentstv), отримайте посилання і передавайте його всім клієнтам протягом одного сезону.

Через сезон у кабінеті буде видно реальні числа саме вашої аудиторії, а не припущення з цієї статті. Аж тоді має сенс вирішувати, чи додавати сертифікати й у якому обсязі, бо це вже рішення з відомими вхідними даними.

